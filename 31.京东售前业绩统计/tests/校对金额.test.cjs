#!/usr/bin/env node
// 31号 · 「校对金额」核心逻辑的本地 mock 测试（不连浏览器、不读 xlsx）。
// 为什么要它：校对是涉工资的最后一道闸；参数/日期/差异率/超阈值/对比/输出一旦被改坏，
// 要么漏报差异、要么误报，直接误导工资。这里用 mock 数据把纯逻辑锁住。
// 用法：node tests/校对金额.test.cjs
const {
  解析参数, 解析年月, 金额, 到分, 算差异率, 超阈值, 归一清单, 对比, 生成Markdown, 页面校验
} = require("../scripts/校对金额.cjs");

let 通过 = 0;
let 失败 = 0;
function 断言(条件, 名称, 详情 = "") {
  if (条件) { 通过 += 1; console.log(`  ✓ ${名称}`); }
  else { 失败 += 1; console.error(`  ✗ ${名称}${详情 ? " —— " + 详情 : ""}`); }
}
function 抛错(fn) {
  try { fn(); return null; } catch (e) { return e; }
}

console.log("== 解析参数 ==");
{
  const 全 = 解析参数(["--年月", "2026-09", "--store", "jd8", "--本地文件", "runtime/downloads/2026-09", "--系统来源", "旧页", "--输出", "runtime/校对-x"]);
  断言(全.年月 === "2026-09" && 全.store === "jd8" && 全.本地文件 === "runtime/downloads/2026-09" && 全.系统来源 === "旧页" && 全.输出 === "runtime/校对-x", "全参数解析", JSON.stringify(全));
  const 默认 = 解析参数(["--年月", "2026-09"]);
  断言(默认.系统来源 === "新页" && 默认.跳过系统 === false && 默认.不截图 === false, "默认系统来源=新页");
  断言(解析参数(["--年月", "2026-09", "--跳过系统", "--不截图"]).跳过系统 === true, "--跳过系统/--不截图 开关");
  断言(解析参数(["--help"]).帮助 === true, "--help 不要求 --年月");
  断言(抛错(() => 解析参数([])) !== null, "缺 --年月 报错");
  断言(抛错(() => 解析参数(["--年月", "2026/09"])) !== null, "年月格式不对报错");
  断言(抛错(() => 解析参数(["--年月", "2026-09", "--系统来源", "双页"])) !== null, "--系统来源 只收 新页|旧页");
  断言(抛错(() => 解析参数(["--年月", "2026-09", "--乱写"])) !== null, "未知参数报错");
}

console.log("== 解析年月 ==");
{
  const a = 解析年月("2026-09");
  断言(a.start === "2026-09-01" && a.end === "2026-09-30", "2026-09 → 09-01~09-30", JSON.stringify(a));
  断言(解析年月("2026-02").end === "2026-02-28", "2026-02 → 28 日");
  断言(解析年月("2024-02").end === "2024-02-29", "2024-02（闰年）→ 29 日");
  断言(解析年月("2026-12").end === "2026-12-31", "2026-12 → 31 日");
  断言(抛错(() => 解析年月("2026-13")) !== null, "13 月报错");
  断言(抛错(() => 解析年月("202609")) !== null, "无横杠报错");
}

console.log("== 金额 / 差异率 / 超阈值 ==");
{
  断言(金额("1,234.5") === 1234.5 && 金额("") === 0 && 金额(undefined) === 0, "金额：逗号串/空/undefined");
  断言(到分(0.1 + 0.2) === 0.3, "到分：0.1+0.2 → 0.3");
  断言(算差异率(100, 100) === 0, "差异率：相同 → 0");
  断言(算差异率(101, 100) === 1, "差异率：+1%");
  断言(算差异率(100, 101) === -0.99, "差异率：-0.99%");
  断言(算差异率(0, 0) === 0, "差异率：0/0 → 0");
  断言(算差异率(5, 0) === null, "差异率：系统 0 本地非 0 → null");
  断言(超阈值(101, 100) === true, "超阈值：正好 1% → 超");
  断言(超阈值(100.5, 100) === false, "超阈值：0.5% → 不超");
  断言(超阈值(100, 101) === false, "超阈值：-0.99% → 不超");
  断言(超阈值(98.99, 100) === true, "超阈值：-1.01% → 超");
  断言(超阈值(0, 0) === false && 超阈值(5, 0) === true && 超阈值(0, 5) === true, "超阈值：0 边界");
}

console.log("== 归一清单 ==");
{
  const a = 归一清单({ 年月: "2026-09", files: [{ file: "a.xlsx", store: "京东1店" }] });
  断言(a.yearMonth === "2026-09" && a.files[0].key === "", "兼容「年月」写法 + key 缺省");
  const b = 归一清单({ yearMonth: "2026-10", files: [{ file: "b.xlsx", store: "京东2店", key: "jd2" }] });
  断言(b.yearMonth === "2026-10" && b.files[0].key === "jd2", "兼容 yearMonth + key");
}

