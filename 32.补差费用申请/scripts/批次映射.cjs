#!/usr/bin/env node
// 32号 补差费用申请：「源表行 → 目标表行」的批次映射（2026-10-08.6 新增，防 10-08 插图事故重演）。
//
// 为什么要有它：10-08 14:44「插图」把数据文件里的**源表行号**（451…462）当成了目标表行号，
//   写进目标表同号的无关行（C454/C456/C460 三格 2022 年老记录被盖）。
//   本模块按**批次记录的数字**推目标行，不硬编码偏移量：
//     目标首行 = 批次.预期末行.汇总 + 1        （写前末行 1672 → 目标首行 1673）
//     目标末行 = 目标首行 + 批次.行数 - 1      （1673+13-1 = 1685）
//     目标行   = 目标首行 + 明细[].源行号 里的序号（明细顺序 = 源表行序；8 月批回归测试保证）
//   （等价说法：目标首行 = 写后 live 末行 - 行数 + 1 = 1685-13+1 = 1673。）
//
// 批次文件 = `准备月度数据.cjs` 产出的 `runtime/待写数据/<月份>.json`：
//   { 行数, 预期末行: { 汇总, 集团, 器械 }, 明细: [ { 源行号, … }, … ], … }
//
// 用法（两个消费方）：
//   scripts/导出收款码图.cjs --清单 <源行清单> --批次 <待写数据.json> --出 <目录>   # 产出带目标行的 dataURL
//   scripts/写入在线表.cjs   --模式 插图 --数据 <dataURL.json> --批次 <待写数据.json> # 核对/映射后再调插图
// 失败一律抛错，不猜、不兜底、不自动重试。
const fs = require("node:fs");
const path = require("node:path");

// 读批次文件 → { 写前置末, 目标首行, 目标末行, 行数, 源行到目标: Map, 文件 }
function 读批次(批, 来源 = "") {
  if (!批) throw new Error("没有批次数据（先给 --批次 <待写数据.json>）");
  const 写前置末 = Number(批.预期末行 && 批.预期末行.汇总);
  const 明细 = Array.isArray(批.明细) ? 批.明细 : [];
  const 行数 = Number(批.行数 || 明细.length);
  if (!Number.isFinite(写前置末) || 写前置末 < 0) {
    throw new Error("批次文件里没有可用的 预期末行.汇总（拿不到目标首行，拒绝猜）");
  }
  if (!(行数 > 0) || !Number.isFinite(行数)) {
    throw new Error("批次文件里没有可用的 行数（拿不到目标末行，拒绝猜）");
  }
  if (明细.length !== 行数) {
    throw new Error(`批次文件自相矛盾：行数 ${行数} 与 明细 ${明细.length} 条不一致`);
  }
  const 目标首行 = 写前置末 + 1;
  const 目标末行 = 目标首行 + 行数 - 1;
  const 源行到目标 = new Map();
  明细.forEach((x, i) => {
    const 源行 = Number(x && x.源行号);
    if (!Number.isFinite(源行)) throw new Error(`批次明细第 ${i + 1} 条没有 源行号`);
    源行到目标.set(源行, 目标首行 + i);
  });
  return { 写前置末, 目标首行, 目标末行, 行数, 源行到目标, 文件: 来源 };
}

// 从文件读（路径相对调用方给的基准目录解析；调用方自己 resolve）
function 读批次文件(路径) {
  const 全路径 = path.resolve(路径);
  if (!fs.existsSync(全路径)) throw new Error(`批次文件不存在：${全路径}`);
  return 读批次(JSON.parse(fs.readFileSync(全路径, "utf8")), 全路径);
}

module.exports = { 读批次, 读批次文件 };
