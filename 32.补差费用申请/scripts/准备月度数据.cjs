// 「读对照」结果 → 对照映射。形状/口径任何一处不对都抛错（fail-loud，不猜、不兜底）。
// 返回 { 映射: Map<源表店铺名, 行>, 行数, 进子表数, 不进行数 }
function 构建对照映射(读结果) {
  if (!读结果 || typeof 读结果 !== "object") {
    throw new Error("读对照 没返回结果对象：读不到在线『店铺-主体对照』子表就停下问人（不许退回硬编码）");
  }
  if (读结果.存在 === false) {
    throw new Error("在线子表『店铺-主体对照』不存在（读对照 返回 存在:false）：请维护人先建好表再跑，不猜");
  }
  const 原始行列表 = 读结果.行列表;
  if (!Array.isArray(原始行列表) || !原始行列表.length) {
    throw new Error("在线子表『店铺-主体对照』没有数据行：请维护人先填好对照再跑，不猜");
  }
  const 有表头 = Array.isArray(原始行列表[0]) && 清理(原始行列表[0][0]) === "源表店铺名";
  const 数据行 = 有表头 ? 原始行列表.slice(1) : 原始行列表;
  if (!数据行.length) throw new Error("在线子表『店铺-主体对照』只有表头、没有店铺行：停下问人，不猜");
  if (Number.isFinite(Number(读结果.数据行数)) && Number(读结果.数据行数) !== 数据行.length) {
    throw new Error(`读对照 行数对不上（报告 ${读结果.数据行数} 行，实际 ${数据行.length} 行）：疑似截断，停手`);
  }
  const 映射 = new Map();
  let 进子表数 = 0;
  for (let i = 0; i < 数据行.length; i += 1) {
    const 行 = 数据行[i];
    const 号 = i + 1;
    if (!Array.isArray(行) || 行.length !== 5) {
      throw new Error(`对照第 ${号} 行不是 5 列（源表店铺名|目标表店铺名|主体|是否进主体子表|备注）：停手`);
    }
    const [源, 目标, 主体, 进, 备注] = 行.map(清理);
    if (!源) throw new Error(`对照第 ${号} 行「源表店铺名」为空：停手`);
    if (!目标) throw new Error(`对照第 ${号} 行店铺「${源}」的「目标表店铺名」为空：停手`);
    if (主体 && !主体白名单.includes(主体)) {
      throw new Error(`对照第 ${号} 行店铺「${源}」的主体「${主体}」不在白名单：停手问人`);
    }
    if (!(进 === "是" || 进.startsWith("否"))) {
      throw new Error(`对照第 ${号} 行店铺「${源}」的「是否进主体子表」只能 是/否，收到「${进}」：停手`);
    }
    if (进 === "是" && !进子表主体.includes(主体)) {
      throw new Error(`对照第 ${号} 行店铺「${源}」写着进子表，但主体「${主体}」不是两个主体子表之一：停手`);
    }
    if (进 !== "是" && 进子表主体.includes(主体)) {
      throw new Error(`对照第 ${号} 行店铺「${源}」主体是「${主体}」却写着不进子表（${进}）：停手`);
    }
    if (映射.has(源)) throw new Error(`对照第 ${号} 行店铺「${源}」重复出现（对照要一店一行）：停手`);
    映射.set(源, { 源店铺名: 源, 目标店铺名: 目标, 主体, 是否进主体子表: 进, 进子表: 进 === "是", 备注 });
    if (进 === "是") 进子表数 += 1;
  }
  return { 映射, 行数: 映射.size, 进子表数, 不进行数: 映射.size - 进子表数 };
}

// 店铺 → 对照行；找不到 / 主体空 → 抛错停下（fail-loud，禁止猜）
function 查对照(对照映射, 店铺) {
  const 行 = 对照映射 instanceof Map ? 对照映射.get(店铺) : null;
  if (!行) {
    throw new Error(`店铺「${店铺}」在在线『店铺-主体对照』子表里找不到（新增/改名/写错？）：不猜——请维护人加进子表后再跑`);
  }
  if (!行.主体) {
    throw new Error(`店铺「${店铺}」在对照子表里「主体」为空（是否进主体子表=${行.是否进主体子表}；备注：${行.备注 || "无"}）：不猜——请人工确认主体后再跑`);
  }
  return 行;
}

// 原硬编码参照（只给 对账 用）：返回 null = 旧表不认识这家店（旧工具会抛错停下）
function 查原硬编码(店铺) {
  const 目标 = 原硬编码店铺规范化[店铺] || 店铺;
  for (const [主体, 店铺清单] of Object.entries(原硬编码主体表)) {
    if (店铺清单.includes(目标)) return { 目标店铺名: 目标, 主体, 进子表: true };
  }
  return null;
}

// 预演期并行对账：把「读表结果（新）」与「原硬编码结果（旧）」按本批出现过的店铺逐一比较。
// 返回差异数组；空数组 = 一致。差异条目：{ 源店铺名, 旧, 新, 变化[] }
function 对账比较(店铺清单, 对照映射) {
  const 差异 = [];
  for (const 店 of 店铺清单) {
    const 新行 = 对照映射 instanceof Map ? 对照映射.get(店) : null;
    const 新 = 新行 ? { 目标店铺名: 新行.目标店铺名, 主体: 新行.主体, 进子表: 新行.进子表 } : null;
    const 旧 = 查原硬编码(店);
    const 变化 = [];
    if (!新) 变化.push("新表：找不到");
    if (!旧) 变化.push("旧硬编码：无归属（原工具会抛错停下）");
    if (新 && 旧) {
      if (新.目标店铺名 !== 旧.目标店铺名) 变化.push(`店铺名「${旧.目标店铺名}」→「${新.目标店铺名}」`);
      if (新.主体 !== 旧.主体) 变化.push(`主体「${旧.主体 || "空"}」→「${新.主体 || "空"}」`);
      if (新.进子表 !== 旧.进子表) 变化.push(`进主体子表「${旧.进子表 ? "是" : "否"}」→「${新.进子表 ? "是" : "否"}」`);
    }
    if (变化.length) 差异.push({ 源店铺名: 店, 旧, 新, 变化 });
  }
  return 差异;
}

