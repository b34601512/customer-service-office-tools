function 取格(行, 列) {
  const v = 行[列];
  return v === undefined || v === null ? "" : String(v).trim();
}

// "2026/9/14" / "2026/09/14" → {年,月}
function 解析付款时间(文本) {
  const 匹配 = /^(\d{4})[\/\-](\d{1,2})([\/\-](\d{1,2}))?/.exec(String(文本 || "").trim());
  if (!匹配) return null;
  return { 年: Number(匹配[1]), 月: Number(匹配[2]) };
}

function 今天年月日() {
  const 现在 = new Date();
  return `${现在.getFullYear()}/${现在.getMonth() + 1}/${现在.getDate()}`;
}

function 上月(今天 = new Date()) {
  const d = new Date(今天.getFullYear(), 今天.getMonth() - 1, 1);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
}

function 查主体(店铺) {
  for (const [主体, 店铺清单] of Object.entries(主体表)) {
    if (店铺清单.includes(店铺)) return 主体;
  }
  if (康健体系店铺.includes(店铺)) {
    throw new Error(`店铺「${店铺}」属于康健体系：历史上有主体记录但没有对应子表，本工具不猜——请人工确认这些行怎么处理`);
  }
  throw new Error(`店铺「${店铺}」没有主体归属记录：不猜，请人工确认（先查目标汇总的历史 店铺→主体）`);
}

function 整理行(源行, { 月份, 申请日期 }) {
  const 店铺 = 店铺规范化[取格(源行, 源列.店铺)] || 取格(源行, 源列.店铺);
  if (!店铺) throw new Error("有行的店铺为空，不猜——请人工确认");
  const 主体 = 查主体(店铺);
  const 汇总行 = [
    取格(源行, 源列.购买日期), 取格(源行, 源列.收款人), 取格(源行, 源列.账号), 店铺,
    取格(源行, 源列.订单号), 取格(源行, 源列.产品), 取格(源行, 源列.类型), 取格(源行, 源列.金额),
    取格(源行, 源列.订单状态), 取格(源行, 源列.转账单号), 取格(源行, 源列.原因), 取格(源行, 源列.责任部门),
    主体, 申请日期, "", "", "", ""
  ];
  const 主体行 = [
    取格(源行, 源列.收款人), 取格(源行, 源列.账号), 店铺, 取格(源行, 源列.订单号), 取格(源行, 源列.产品),
    取格(源行, 源列.类型), 取格(源行, 源列.金额), 取格(源行, 源列.订单状态), 取格(源行, 源列.转账单号),
    取格(源行, 源列.原因), 取格(源行, 源列.责任部门), ""
  ];
  return { 源行号: 源行.__行号, 付款时间: 取格(源行, 源列.付款时间), 店铺, 主体, 汇总行, 主体行 };
}

// 主流程：返回 { 月份, 申请日期, 行数, 合计金额, 汇总行, 集团, 器械, 明细 }
function 准备月度数据({ 源矩阵, 月份, 申请日期 = 今天年月日(), 排除已存在订单 = new Set() }) {
  if (!Array.isArray(源矩阵) || !源矩阵.length) throw new Error("源矩阵为空");
  const [年, 月] = String(月份).split("-").map(Number);
  if (!年 || !月) throw new Error(`--月份 格式应为 YYYY-MM，收到「${月份}」`);
  const 命中 = [];
  for (let i = 2; i < 源矩阵.length; i += 1) {
    const 行 = 源矩阵[i];
    if (!Array.isArray(行)) continue;
    const 付 = 解析付款时间(取格(行, 源列.付款时间));
    if (!付 || 付.年 !== 年 || 付.月 !== 月) continue;
    const 行副本 = 行.slice();
    行副本.__行号 = i + 1;
    命中.push(行副本);
  }

  const 明细 = [];
  const 重复 = [];
  for (const 行 of 命中) {
    const 订单 = 取格(行, 源列.订单号);
    if (订单 && 排除已存在订单.has(订单)) { 重复.push({ 源行号: 行.__行号, 订单 }); continue; }
    明细.push(整理行(行, { 月份, 申请日期 }));
  }
  if (重复.length) {
    throw new Error(`有 ${重复.length} 行订单号已存在于目标汇总（防重复导入）：` +
      重复.map((x) => `源R${x.源行号}/${x.订单}`).join("、"));
  }

  const 集团 = 明细.filter((x) => x.主体 === "深圳市德达医疗科技集团有限公司");
  const 器械 = 明细.filter((x) => x.主体 === "深圳市德达医疗器械有限公司");
  const 合计 = (清单) => Math.round(清单.reduce((s, x) => s + Number(x.汇总行[7] || 0), 0) * 100) / 100;

  return {
    月份, 申请日期,
    行数: 明细.length,
    合计金额: 合计(明细),
    明细,
    汇总行: 明细.map((x) => x.汇总行),
    主体: {
      "深圳市德达医疗科技集团有限公司": { 行数: 集团.length, 合计金额: 合计(集团), 行: 集团.map((x) => x.主体行) },
      "深圳市德达医疗器械有限公司": { 行数: 器械.length, 合计金额: 合计(器械), 行: 器械.map((x) => x.主体行) }
    }
  };
}

// CLI
function 解析参数(argv) {
  const 参数 = {};
  for (let i = 0; i < argv.length; i += 1) {
    const t = argv[i];
    if (!t.startsWith("--")) continue;
    const k = t.slice(2); const v = argv[i + 1]; i += 1;
    if (k === "源") 参数.源 = v;
    else if (k === "月份") 参数.月份 = v;
    else if (k === "申请日期") 参数.申请日期 = v;
    else if (k === "落盘") 参数.落盘 = v;
    else if (k === "预期汇总末行") 参数.预期汇总末行 = Number(v);
    else if (k === "预期集团末行") 参数.预期集团末行 = Number(v);
    else if (k === "预期器械末行") 参数.预期器械末行 = Number(v);
  }
  return 参数;
}

function main() {
  const 参数 = 解析参数(process.argv.slice(2));
  const 源路径 = path.resolve(项目根, 参数.源 || path.join("runtime", "侦察", "2026-10-08", "源表-汇总.json"));
  const 月份 = 参数.月份 || 上月();
  const 申请日期 = 参数.申请日期 || 今天年月日();
  if (!fs.existsSync(源路径)) throw new Error(`源表 JSON 不存在：${源路径}（先用 24号 read-kdocs.js 读源表 --out）`);
  const 源 = JSON.parse(fs.readFileSync(源路径, "utf8"));
  const 结果 = 准备月度数据({ 源矩阵: 源.matrix || 源, 月份, 申请日期 });
  if (参数.预期汇总末行 || 参数.预期集团末行 || 参数.预期器械末行) {
    结果.预期末行 = { 汇总: 参数.预期汇总末行 || 0, 集团: 参数.预期集团末行 || 0, 器械: 参数.预期器械末行 || 0 };
  }

  const 落盘路径 = path.resolve(项目根, 参数.落盘 || path.join("runtime", "待写数据", `${月份}.json`));
  fs.mkdirSync(path.dirname(落盘路径), { recursive: true });
  fs.writeFileSync(落盘路径, JSON.stringify(结果, null, 2), "utf8");

  console.log(`\n  32号 月度数据准备：${月份}（申请日期 ${申请日期}）`);
  console.log(`  源表：${path.relative(项目根, 源路径)}`);
  console.log(`  命中 ${结果.行数} 行，合计 ¥${结果.合计金额}`);
  for (const [主体, 组] of Object.entries(结果.主体)) {
    console.log(`    · ${主体}：${组.行数} 行 / ¥${组.合计金额}`);
  }
  console.log(`  已落盘：${path.relative(项目根, 落盘路径)}\n`);
  for (const 行 of 结果.明细) {
    console.log(`    源R${行.源行号} ${行.付款时间} ${行.店铺} ${行.汇总行[1]} ¥${行.汇总行[7]} ${行.汇总行[6]} → ${行.主体.slice(6, 12)}`);
  }
  console.log("");
}

module.exports = { 准备月度数据, 主体表, 店铺规范化, 解析付款时间, 上月, 汇总表头, 主体表头 };

