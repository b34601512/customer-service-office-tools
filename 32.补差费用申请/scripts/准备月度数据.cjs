// 主流程：返回 { 月份, 申请日期, 行数, 合计金额, 明细, 汇总行, 主体, 不进子表, 对照, 对账? }
//   对照 = 构建对照映射(...) 的结果（必须给；产出只认在线子表）
function 准备月度数据({ 源矩阵, 月份, 申请日期 = 今天年月日(), 排除已存在订单 = new Set(), 对照, 对账 = true }) {
  if (!对照 || !(对照.映射 instanceof Map)) {
    throw new Error("没有对照映射：本工具只认在线『店铺-主体对照』子表（读不到就停下问人，不许退回硬编码）");
  }
  if (!Array.isArray(源矩阵) || !源矩阵.length) throw new Error("源矩阵为空");
  const [年, 月] = String(月份).split("-").map(Number);
  if (!年 || !月 || 月 < 1 || 月 > 12) throw new Error(`--月份 格式应为 YYYY-MM，收到「${月份}」`);

  const 命中 = [];
  for (let i = 2; i < 源矩阵.length; i += 1) {
    const 行 = 源矩阵[i];
    if (!Array.isArray(行)) continue;
    const 付 = 解析付款时间(取格(行, 源列.付款时间));
    if (!付 || 付.年 !== 年 || 付.月 !== 月) continue;
    const 行副本 = 行.slice();
    行副本.__行号 = i + 1;
    命中.push(行副本);
  }

  const 待整理 = [];
  const 重复 = [];
  for (const 行 of 命中) {
    const 订单 = 取格(行, 源列.订单号);
    if (订单 && 排除已存在订单.has(订单)) { 重复.push({ 源行号: 行.__行号, 订单 }); continue; }
    待整理.push(行);
  }
  if (重复.length) {
    throw new Error(`有 ${重复.length} 行订单号已存在于目标汇总（防重复导入）：` +
      重复.map((x) => `源R${x.源行号}/${x.订单}`).join("、"));
  }

  // ── ⑤ 预演期并行对账（默认开）：有差异 = 停下，不产出、不切换生效 ──
  let 对账结果 = null;
  if (对账) {
    const 店铺清单 = [...new Set(待整理.map((行) => 取格(行, 源列.店铺)).filter(Boolean))];
    const 差异 = 对账比较(店铺清单, 对照.映射);
    if (差异.length) {
      const 行文本 = 差异.map((d) => `    · ${d.源店铺名}：${d.变化.join("；")}`).join("\n");
      const 错误 = new Error(
        `预演期并行对账发现 ${差异.length} 个店铺「读表结果 ≠ 原硬编码结果」，不直接切换生效：\n${行文本}\n` +
        `  处理：请人工确认差异后用 --对照 子表 显式切换生效（或把子表改对再重跑）。`
      );
      错误.对账差异 = 差异;
      throw 错误;
    }
    对账结果 = { 通过: true, 比较店铺数: 店铺清单.length, 差异: [] };
  }

  const 明细 = 待整理.map((行) => 整理行(行, { 申请日期, 对照映射: 对照.映射 }));
  const 合计 = (清单) => Math.round(清单.reduce((s, x) => s + Number(x.汇总行[7] || 0), 0) * 100) / 100;
  const 集团 = 明细.filter((x) => x.进子表 && x.主体 === 集团主体);
  const 器械 = 明细.filter((x) => x.进子表 && x.主体 === 器械主体);
  const 不进 = 明细.filter((x) => !x.进子表);

  return {
    月份, 申请日期,
    行数: 明细.length,
    合计金额: 合计(明细),
    明细,
    汇总行: 明细.map((x) => x.汇总行),
    主体: {
      [集团主体]: { 行数: 集团.length, 合计金额: 合计(集团), 行: 集团.map((x) => x.主体行) },
      [器械主体]: { 行数: 器械.length, 合计金额: 合计(器械), 行: 器械.map((x) => x.主体行) }
    },
    不进子表: { 行数: 不进.length, 合计金额: 合计(不进) },
    对照: { 来源: "在线子表『店铺-主体对照』", 行数: 对照.行数, 模式: 对账 ? "对账" : "子表" },
    ...(对账结果 ? { 对账: 对账结果 } : {})
  };
}

// CLI
function 解析参数(argv) {
  const 参数 = {};
  for (let i = 0; i < argv.length; i += 1) {
    const t = argv[i];
    if (!t.startsWith("--")) continue;
    const k = t.slice(2); const v = argv[i + 1]; i += 1;
    if (k === "源") 参数.源 = v;
    else if (k === "月份") 参数.月份 = v;
    else if (k === "申请日期") 参数.申请日期 = v;
    else if (k === "落盘") 参数.落盘 = v;
    else if (k === "对照") 参数.对照 = v;
    else if (k === "预期汇总末行") 参数.预期汇总末行 = Number(v);
    else if (k === "预期集团末行") 参数.预期集团末行 = Number(v);
    else if (k === "预期器械末行") 参数.预期器械末行 = Number(v);
  }
  return 参数;
}

function 写证据(目录, 名称, 数据) {
  fs.mkdirSync(目录, { recursive: true });
  const 文件 = path.join(目录, 名称 + ".json");
  fs.writeFileSync(文件, JSON.stringify({ 时间: new Date().toISOString(), ...数据 }, null, 2), "utf8");
  return 文件;
}

// 命令行主流程（deps 注入供测试：读在线对照 / 证据目录）
async function 跑命令行(argv, deps = {}) {
  const 参数 = 解析参数(argv);
  const 源路径 = path.resolve(项目根, 参数.源 || path.join("runtime", "侦察", "2026-10-08", "源表-汇总.json"));
  const 月份 = 参数.月份 || 上月();
  const 申请日期 = 参数.申请日期 || 今天年月日();
  const 对照模式 = 参数.对照 || "对账";
  if (!(对照模式 === "对账" || 对照模式 === "子表")) {
    throw new Error(`--对照 只能是 对账 | 子表（收到「${对照模式}」）：对账=预演期逐店对账，子表=显式切换生效`);
  }
  if (!/^\d{4}-\d{1,2}$/.test(String(月份))) throw new Error(`--月份 格式应为 YYYY-MM，收到「${月份}」`);
  const [年, 月] = String(月份).split("-").map(Number);
  if (月 < 1 || 月 > 12) throw new Error(`--月份 格式应为 YYYY-MM，收到「${月份}」`);
  if (!fs.existsSync(源路径)) throw new Error(`源表 JSON 不存在：${源路径}（先用 24号 read-kdocs.js 读源表 --out）`);
  const 源 = JSON.parse(fs.readFileSync(源路径, "utf8"));

  // ★ 对照只认在线子表：读不到/表不存在/缺店/主体空 → 抛错停下（绝不退回硬编码）
  const 读结果 = typeof deps.读在线对照 === "function" ? await deps.读在线对照() : await 读在线对照(deps);
  const 对照 = 构建对照映射(读结果);
  const 时间戳 = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
  const 证据目录 = deps.证据目录 || path.join(项目根, "runtime", "证据", 时间戳 + "-准备月度数据");
  写证据(证据目录, "0-读对照", {
    来源: "店铺主体对照.cjs → AirScript 读对照", 行数: 对照.行数,
    进子表数: 对照.进子表数, 不进行数: 对照.不进行数, 行列表: 读结果.行列表
  });

  let 结果;
  try {
    结果 = 准备月度数据({
      源矩阵: 源.matrix || 源, 月份, 申请日期, 对照, 对账: 对照模式 === "对账"
    });
  } catch (错误) {
    if (错误 && 错误.对账差异) 写证据(证据目录, "1-对账差异", { 月份, 差异: 错误.对账差异 });
    throw 错误;
  }
  if (结果.对账) 写证据(证据目录, "1-对账", { 月份, ...结果.对账 });

  if (参数.预期汇总末行 || 参数.预期集团末行 || 参数.预期器械末行) {
    结果.预期末行 = { 汇总: 参数.预期汇总末行 || 0, 集团: 参数.预期集团末行 || 0, 器械: 参数.预期器械末行 || 0 };
  }

  const 落盘路径 = path.resolve(项目根, 参数.落盘 || path.join("runtime", "待写数据", `${月份}.json`));
  fs.mkdirSync(path.dirname(落盘路径), { recursive: true });
  fs.writeFileSync(落盘路径, JSON.stringify(结果, null, 2), "utf8");

  console.log(`\n  32号 月度数据准备：${月份}（申请日期 ${申请日期}）`);
  console.log(`  对照来源：${结果.对照.来源} ${对照.行数} 店（进子表 ${对照.进子表数} / 不进 ${对照.不进行数}）`);
  if (结果.对账) {
    console.log(`  对账：与硬编码逐店一致（${结果.对账.比较店铺数} 店）= 差异 0，可切换到 --对照 子表`);
  } else {
    console.log(`  对账：已用 --对照 子表 显式切换（跳过与硬编码对账）`);
  }
  console.log(`  源表：${path.relative(项目根, 源路径)}`);
  console.log(`  命中 ${结果.行数} 行，合计 ¥${结果.合计金额}`);
  for (const [主体, 组] of Object.entries(结果.主体)) {
    console.log(`    · ${主体}：${组.行数} 行 / ¥${组.合计金额}`);
  }
  if (结果.不进子表 && 结果.不进子表.行数) {
    console.log(`    · 不进主体子表：${结果.不进子表.行数} 行 / ¥${结果.不进子表.合计金额}（只进汇总）`);
  }
  console.log(`  已落盘：${path.relative(项目根, 落盘路径)}`);
  console.log(`  证据：${path.relative(项目根, 证据目录)}`);

  // 带图清单（2026-10-08 起自动生成，不再手工攒）：本批源表 G 列是 DISPIMG 图的行 → 源行/姓名/ID/目标行。
  // 目标行要拿 预期末行.汇总 推；没给就先只提示，跑 同步收款码图.cjs 时仍会按批次文件再算。
  if (结果.预期末行 && 结果.预期末行.汇总) {
    const 清单 = 从批次生成清单(结果, { 文件: 落盘路径 });
    const 图文件 = 清单路径(项目根, 结果.月份);
    写清单(图文件, 清单);
    console.log(`  带图清单：${清单.有图行数}/${结果.行数} 行有收款码图 → ${path.relative(项目根, 图文件)}`);
    for (const 一 of 清单.项) console.log(`    · 源R${一.源行} ${一.姓名} → 目标行 ${一.目标行}`);
    if (清单.有图行数) console.log(`    下一步（缩略图→一把插→回读一键）：node scripts/同步收款码图.cjs --批次 ${path.relative(项目根, 落盘路径)}`);
    console.log("");
  } else {
    const 有图行数 = (结果.明细 || []).filter((x) => 解析DISPIMG((x.汇总行 || [])[2])).length;
    if (有图行数) console.log(`  提示：本批有 ${有图行数} 行带收款码图；没给 --预期汇总末行，目标行等跑 同步收款码图.cjs 时再算。\n`);
  }

  for (const 行 of 结果.明细) {
    const 归属 = 行.进子表 ? 行.主体.slice(6, 12) : `不进子表（${行.主体.slice(6, 12) || "无主体"}）`;
    console.log(`    源R${行.源行号} ${行.付款时间} ${行.店铺} ${行.汇总行[1]} ¥${行.汇总行[7]} ${行.汇总行[6]} → ${归属}`);
  }
  console.log("");
  return { 结果, 落盘路径, 证据目录, 对照 };
}

async function main() {
  await 跑命令行(process.argv.slice(2));
}

