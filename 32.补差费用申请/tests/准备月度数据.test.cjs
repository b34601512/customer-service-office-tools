// 本机 runtime/证据 里最近一次「读对照」结果（跑过在线读才有；没有就跳过）
function 找最新读对照证据() {
  const 根 = path.join(项目根, "runtime", "证据");
  if (!fs.existsSync(根)) return null;
  const 目录们 = fs.readdirSync(根)
    .filter((n) => n.endsWith("-店铺主体对照") || n.endsWith("-准备月度数据"))
    .sort().reverse();
  for (const 名 of 目录们) {
    const p = path.join(根, 名, "2-读对照.json");
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, "utf8"));
  }
  return null;
}

function 跑CLI(参数) {
  try {
    execFileSync(process.execPath, [path.join("scripts", "准备月度数据.cjs"), ...参数],
      { cwd: 项目根, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
    return { 码: 0, 输出: "" };
  } catch (e) {
    return { 码: typeof e.status === "number" ? e.status : -1, 输出: String(e.stderr || "") + String(e.stdout || "") };
  }
}

