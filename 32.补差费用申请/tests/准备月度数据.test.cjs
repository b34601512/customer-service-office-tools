#!/usr/bin/env node
// 32号 数据准备回归测试：拿「8 月批次」（已人工导入过、有历史结果可对账）验证映射：
//   期待：准备月度数据(2026-08, 申请日期 2026/9/3) 的输出 == 目标表里 8 月批次的实际内容
//   （汇总 R1648~R1672 的 A~N + 两个主体子表的 A~L）
// 快照是本机 runtime 里的只读导出（不入库）；缺快照就跳过并说明。
//
// 跑：node tests/准备月度数据.test.cjs
const fs = require("node:fs");
const path = require("node:path");
const { 准备月度数据 } = require("../scripts/准备月度数据.cjs");

const 项目根 = path.resolve(__dirname, "..");
const 快照目录 = path.join(项目根, "runtime", "侦察", "2026-10-08");

let 通过 = 0; let 失败 = 0;
function 断言(条件, 说明, 实测 = "") {
  if (条件) { 通过 += 1; console.log(`  ✓ ${说明}`); }
  else { 失败 += 1; console.log(`  ✗ ${说明}${实测 ? `｜实测：${实测}` : ""}`); }
}
function 逐格对比(期望行, 实际行, 列数, 标签) {
  const 差异 = [];
  for (let c = 0; c < 列数; c += 1) {
    const a = String(期望行[c] === undefined ? "" : 期望行[c]).trim();
    const b = String(实际行[c] === undefined ? "" : 实际行[c]).trim();
    if (a !== b) 差异.push(`C${c + 1} 期望[${a}] 实际[${b}]`);
  }
  return { 同: 差异.length === 0, 差异 };
}

function 读(文件) {
  const p = path.join(快照目录, 文件);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

function main() {
  console.log("\n32号 准备月度数据 回归测试（对账 8 月批次）\n");
  const 源 = 读("源表-汇总.json");
  const 目标汇总 = 读("目标-汇总.json");
  const 目标集团 = 读("目标-深圳市德达医疗科技集团有限公司.json");
  const 目标器械 = 读("目标-深圳市德达医疗器械有限公司.json");
  if (!源 || !目标汇总 || !目标集团 || !目标器械) {
    console.log("  跳过：缺少本机快照 runtime/侦察/2026-10-08/*.json（先跑 24号 read-kdocs.js 导出）\n");
    process.exitCode = 0;
    return;
  }

  // ── 1) 8 月批次：与历史实际对账 ─────────────────────────────────────────────
  const 八月 = 准备月度数据({ 源矩阵: 源.matrix, 月份: "2026-08", 申请日期: "2026/9/3" });
  断言(八月.行数 === 25, "8月命中 25 行（源 R425~R449）", String(八月.行数));
  断言(八月.合计金额 === 1079.82, "8月合计 ¥1079.82（= 主体表 957.71 + 122.11）", String(八月.合计金额));

  // 汇总：目标 R1648~R1672 应与我们的 25 行一致（A~N 14 列；O~R 应为空）
  const 汇总起点 = 1648;
  let 汇总错 = 0;
  for (let i = 0; i < 八月.汇总行.length; i += 1) {
    const 实际 = 目标汇总.matrix[汇总起点 - 1 + i];
    const r = 逐格对比(八月.汇总行[i], 实际, 14, `汇总行${i + 1}`);
    if (!r.同) { 汇总错 += 1; if (汇总错 <= 3) console.log(`    ! 汇总第${i + 1}行（R${汇总起点 + i}）：${r.差异.join("；")}`); }
    for (let c = 14; c < 18; c += 1) {
      if (String(实际[c] || "").trim()) console.log(`    ! 汇总 R${汇总起点 + i} 的 O~R 不该有值：C${c + 1}=${实际[c]}`);
    }
  }
  断言(汇总错 === 0, "8月 25 行 × 汇总 A~N 全对（对账历史实际）", `${汇总错} 行有差异`);

  // 主体子表：集团 = 目标集团 R4~R19、器械 = 目标器械 R4~R12（A~L）
  for (const [主体, 快照, 起行, 止行] of [
    ["深圳市德达医疗科技集团有限公司", 目标集团, 4, 19],
    ["深圳市德达医疗器械有限公司", 目标器械, 4, 12]
  ]) {
    const 组 = 八月.主体[主体];
    断言(组.行数 === 止行 - 起行 + 1, `${主体} 8月 ${组.行数} 行（${起行}~${止行}）`, String(组.行数));
    let 错 = 0;
    for (let i = 0; i < 组.行.length; i += 1) {
      const 实际 = 快照.matrix[起行 - 1 + i];
      const r = 逐格对比(组.行[i], 实际, 12, `${主体}行${i + 1}`);
      if (!r.同) { 错 += 1; if (错 <= 3) console.log(`    ! ${主体}第${i + 1}行（R${起行 + i}）：${r.差异.join("；")}`); }
    }
    断言(错 === 0, `${主体} 8月 A~L 全对（对账历史实际）`, `${错} 行有差异`);
  }

  // ── 2) 9 月批次：本次要写的 ───────────────────────────────────────────────
  const 九月 = 准备月度数据({ 源矩阵: 源.matrix, 月份: "2026-09" });
  断言(九月.行数 === 13, "9月命中 13 行（源 R450~R462）", String(九月.行数));
  断言(九月.合计金额 === 873.43, "9月合计 ¥873.43", String(九月.合计金额));
  断言(九月.主体["深圳市德达医疗科技集团有限公司"].行数 === 10, "9月 集团 10 行", String(九月.主体["深圳市德达医疗科技集团有限公司"].行数));
  断言(九月.主体["深圳市德达医疗器械有限公司"].行数 === 3, "9月 器械 3 行", String(九月.主体["深圳市德达医疗器械有限公司"].行数));
  断言(九月.主体["深圳市德达医疗科技集团有限公司"].合计金额 === 853.15, "9月 集团合计 ¥853.15");
  断言(九月.主体["深圳市德达医疗器械有限公司"].合计金额 === 20.28, "9月 器械合计 ¥20.28");
  const dyn = 九月.明细.find((x) => x.店铺 === "DY03店德达抖音旗舰店" && x.汇总行[5] === "K-HF53");
  断言(Boolean(dyn), "9月 抖音02店 R461 已规范化为 DY03店德达抖音旗舰店 并归器械");
  // 9月所有订单号不应存在于目标汇总
  const 已有订单 = new Set(目标汇总.matrix.slice(1).map((r) => String(r[4] || "").trim()).filter(Boolean));
  const 撞单 = 九月.明细.filter((x) => 已有订单.has(x.汇总行[4]));
  断言(撞单.length === 0, "9月 13 行订单号都不在目标汇总里（无重复导入）", 撞单.map((x) => x.汇总行[4]).join(","));

  // ── 3) 防呆：没见过 / 康健体系 的行必须抛错 ───────────────────────────────
  const 造行 = (店铺) => {
    const 行 = new Array(21).fill("");
    行[源列(15)] = "2026/9/1"; 行[源列(7)] = 店铺; 行[源列(8)] = "T1"; 行[源列(14)] = "1";
    return 行;
  };
  function 源列(n) { return n; }
  try {
    准备月度数据({ 源矩阵: [[""], ["", ""], 造行("没见过的店")], 月份: "2026-09" });
    断言(false, "未见过的店铺 → 抛错");
  } catch (e) { 断言(e.message.includes("没有主体归属记录"), "未见过的店铺 → 抛错"); }
  try {
    准备月度数据({ 源矩阵: [[""], ["", ""], 造行("德达商城")], 月份: "2026-09" });
    断言(false, "康健体系店铺 → 抛错");
  } catch (e) { 断言(e.message.includes("康健体系"), "康健体系店铺 → 抛错"); }

  console.log(`\n  结果：${通过} 通过 / ${失败} 失败\n`);
  process.exitCode = 失败 ? 1 : 0;
}

main();
