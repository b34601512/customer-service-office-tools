#!/usr/bin/env node
// 32号 缩略图 + 一把插 回归测试（2026-10-08.7，黎路遥 15:57 口径）：
//   ① 缩略尺寸：逐张按原图比例缩、默认宽 320、不放大（原图更小就保持原宽）；
//   ② 体积上限：单张 ≤60KB、整批 ≤1MB（超限必须拦下，不许硬闯）；
//   ③ 批量插图：默认整批一把（7 张 = 1 次请求）、--每批 N 按 N 拆、请求里带批次行域（预期起/止/末行）；
//   ④ 失败停手：某批抛错（限流/HTTP 5xx）→ 证据落盘、不再发后续批、不重试；
//   ⑤ 行结果：跳过/插入报错/新公式都如实回报，给回读校验用。
// 跑：node tests/缩略图与批量插图.test.cjs
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const 项目根 = path.resolve(__dirname, "..");
const { 默认缩略参数, 算缩略尺寸, 估字节, 缩略体积守门, 算批组 } = require(path.join(项目根, "scripts", "缩略图规格.cjs"));
const { 执行插图序列 } = require(path.join(项目根, "scripts", "写入在线表.cjs"));

let 通过 = 0;
let 失败 = 0;
function 断言(条件, 说明, 实测 = "") {
  if (条件) { 通过 += 1; console.log(`  ✓ ${说明}`); }
  else { 失败 += 1; console.log(`  ✗ ${说明}${实测 ? `｜实测：${实测}` : ""}`); }
}

const 样图 = Array.from({ length: 7 }, (_, i) => ({
  行: 1674 + i, // 1674~1680：行域校验只看规.预期起/止，这里用规对象控制
  源行: 451 + i,
  dataURL: "data:image/jpeg;base64," + "A".repeat(256)
}));
const 规 = { 预期起: 1673, 预期止: 1685, 预期末行: 1685, 批次说明: "批次目标行 1673~1685" };
function 新证据目录() { return fs.mkdtempSync(path.join(os.tmpdir(), "32-插图-")); }

// 假服务端：按请求里的 图 数组逐张回报成功/跳过；可指定某一行跳过、或让整个调用抛错。
function 造假服务端(选项 = {}) {
  const 调用 = [];
  const 调 = async (参数) => {
    调用.push(参数);
    const 图 = JSON.parse(参数.图);
    if (选项.抛错) throw new Error(String(选项.抛错));
    const 跳过 = [];
    const 逐行 = [];
    for (const x of 图) {
      if (选项.跳过行 === x.行) { 跳过.push({ 行: x.行, 跳过原因: "假服务端：该格不是 DISPIMG" }); continue; }
      逐行.push({ 行: x.行, 插入: "成功", 旧公式: '=DISPIMG("ID_旧' + x.行 + '",1)', 新公式: '=DISPIMG("ID_新' + x.行 + '",1)' });
    }
    return { scriptVersion: "2026-10-08.6", 模式: "插图", written: 逐行.length > 0, 请求数: 图.length, 成功数: 逐行.length, 插入失败数: 0, 回读不符数: 0, 跳过, 逐行 };
  };
  return { 调, 调用 };
}

async function 主() {
  console.log("\n32号 缩略图 + 一把插 回归测试\n");

  // ── 1) 缩略尺寸（默认 320、不放大、按比例）──────────────────────────────────
  {
    断言(默认缩略参数.宽 === 320 && 默认缩略参数.质量 === 0.75, "默认参数：宽 320 / 质量 0.75", JSON.stringify(默认缩略参数));
    断言(默认缩略参数.单张上限字节 === 60 * 1024 && 默认缩略参数.整批上限字节 === 1024 * 1024, "默认上限：单张 60KB / 整批 1MB");
    const a = 算缩略尺寸(1279, 1744, 320);
    断言(a.宽 === 320 && a.高 === 436, "1279x1744 → 320x436（按比例）", JSON.stringify(a));
    const b = 算缩略尺寸(200, 100, 320);
    断言(b.宽 === 200 && b.高 === 100, "200x100 原图更小 → 不放大（200x100）", JSON.stringify(b));
    let 错 = "";
    try { 算缩略尺寸(1000, 500, 0); } catch (e) { 错 = e.message; }
    断言(/目标宽/.test(错), "目标宽 0 → 抛错（不猜）", 错);
  }

  // ── 2) 估字节 ────────────────────────────────────────────────────────────────
  {
    断言(估字节("data:image/jpeg;base64,AAAA") === 3, "估字节(AAAA) = 3");
    断言(估字节("data:image/jpeg;base64,AA==") === 1, "估字节(AA==) = 1（去 padding）");
    断言(估字节("没有逗号") === 0 && 估字节("") === 0, "估字节(坏串/空) = 0");
  }

  // ── 3) 体积守门：单张 ≤60KB、整批 ≤1MB ──────────────────────────────────────
  {
    const 小 = [{ 行: 1674, 字节: 20000 }, { 行: 1675, 字节: 30000 }];
    const 过 = 缩略体积守门(小, { 单张上限字节: 60 * 1024, 整批上限字节: 1024 * 1024 });
    断言(过.通过 && 过.总字节 === 50000, "两手小图 → 通过", JSON.stringify(过));
    const 单超 = 缩略体积守门([{ 行: 1674, 字节: 20000 }, { 行: 1675, 字节: 61 * 1024 }]);
    断言(!单超.通过 && 单超.失败.some((f) => f.行 === 1675 && /单张/.test(f.原因)), "单张 61KB → 拦下", JSON.stringify(单超.失败));
    const 整超 = 缩略体积守门([{ 行: 1, 字节: 400 * 1024 }, { 行: 2, 字节: 400 * 1024 }, { 行: 3, 字节: 400 * 1024 }]);
    断言(!整超.通过 && 整超.失败.some((f) => f.行 === 0 && /整批/.test(f.原因)), "三张 400KB 合计 1.2MB → 拦下", JSON.stringify(整超.失败));
    断言(缩略体积守门([], {}).通过 && 缩略体积守门([], {}).总字节 === 0, "空数组 → 通过");
  }

  // ── 4) 分组：默认整批一把，--每批 N 拆分 ────────────────────────────────────
  {
    断言(JSON.stringify(算批组(7, 0)) === "[7]", "算批组(7, 0) = 整批一把 [7]");
    断言(JSON.stringify(算批组(7, undefined)) === "[7]", "算批组(7, 未给) = 整批一把 [7]");
    断言(JSON.stringify(算批组(7, 3)) === "[3,3,1]", "算批组(7, 3) = [3,3,1]");
    断言(JSON.stringify(算批组(0, 3)) === "[]", "算批组(0, 3) = []");
    let 错 = ""; try { 算批组(7, -1); } catch (e) { 错 = e.message; }
    断言(/每批/.test(错), "算批组：负数每批 → 抛错", 错);
    错 = ""; try { 算批组(7, 2.5); } catch (e) { 错 = e.message; }
    断言(/每批/.test(错), "算批组：非整数每批 → 抛错", 错);
  }

  // ── 5) 批量插图：默认整批一把（7 张 = 1 次请求） + 证据 7-插图-批量.json ────
  {
    const 证据 = 新证据目录();
    const { 调, 调用 } = 造假服务端();
    const 果 = await 执行插图序列(样图, 规, 证据, { 调脚本: 调 });
    断言(调用.length === 1, "默认整批一把：7 张只发 1 次请求", String(调用.length));
    const 请求图 = JSON.parse(调用[0].图);
    断言(请求图.length === 7 && 请求图[0].行 === 1674 && 请求图[6].行 === 1680, "请求里带全部 7 张（行号按序）", JSON.stringify(请求图.map((x) => x.行)));
    断言(调用[0].预期起 === 1673 && 调用[0].预期止 === 1685 && 调用[0].预期末行 === 1685 && 调用[0].allowWrite === true, "请求带批次行域 + allowWrite", JSON.stringify({ 起: 调用[0].预期起, 止: 调用[0].预期止, 末: 调用[0].预期末行, w: 调用[0].allowWrite }));
    断言(果.成功 === 7 && 果.全合格 === true && 果.批次.length === 1 && 果.行结果.length === 7, "结果：7/7 全合格", JSON.stringify({ 成功: 果.成功, 批: 果.批次.length, 行: 果.行结果.length }));
    断言(fs.existsSync(path.join(证据, "7-插图-批量.json")), "证据文件 7-插图-批量.json 已落盘");
    const 证据体 = JSON.parse(fs.readFileSync(path.join(证据, "7-插图-批量.json"), "utf8"));
    断言(证据体.批次 === 1 && 证据体.张数 === 7 && 证据体.成功数 === 7, "证据内容：批次1 / 7 张 / 成功 7", JSON.stringify({ 批: 证据体.批次, 张: 证据体.张数, 成: 证据体.成功数 }));
    断言(!fs.existsSync(path.join(证据, "7-插图-批量-1.json")), "整批一把时不产生 -1 拆分证据");
  }

  // ── 6) --每批 3：拆 3 批（3/3/1），各自证据 ────────────────────────────────
  {
    const 证据 = 新证据目录();
    const { 调, 调用 } = 造假服务端();
    const 果 = await 执行插图序列(样图, 规, 证据, { 调脚本: 调, 每批: 3 });
    断言(调用.length === 3, "--每批 3 → 3 次请求", String(调用.length));
    断言(JSON.stringify(调用.map((c) => JSON.parse(c.图).length)) === "[3,3,1]", "每批张数 = [3,3,1]", JSON.stringify(调用.map((c) => JSON.parse(c.图).length)));
    断言(果.成功 === 7 && 果.批次.length === 3, "拆批也 7/7 成功", JSON.stringify({ 成功: 果.成功, 批: 果.批次.length }));
    断言(["7-插图-批量-1.json", "7-插图-批量-2.json", "7-插图-批量-3.json"].every((f) => fs.existsSync(path.join(证据, f))), "3 个拆分证据都在");
  }

  // ── 7) 行结果：跳过行如实回报（合格 false + 跳过原因），其余照常 ─────────────
  {
    const 证据 = 新证据目录();
    const { 调 } = 造假服务端({ 跳过行: 1676 });
    const 果 = await 执行插图序列(样图, 规, 证据, { 调脚本: 调 });
    const 跳 = 果.行结果.find((x) => x.行 === 1676);
    断言(果.成功 === 6 && 果.全合格 === false, "有 1 行跳过 → 6/7、全合格 false", JSON.stringify({ 成: 果.成功, 全: 果.全合格 }));
    断言(跳 && !跳.合格 && /不是 DISPIMG/.test(跳.跳过原因), "跳过行：合格 false + 原文原因回传", JSON.stringify(跳));
  }

  // ── 8) 失败停手：第 1 批抛错（限流/5xx）→ 证据留现场、不重试、不发后续批 ────
  {
    const 证据 = 新证据目录();
    const { 调, 调用 } = 造假服务端({ 抛错: "金山接口返回 HTTP 403：ScriptRetryLater" });
    const 果 = await 执行插图序列(样图, 规, 证据, { 调脚本: 调, 每批: 3 });
    断言(调用.length === 1, "抛错后不再发后续批（也不重试）", String(调用.length));
    断言(果.成功 === 0 && 果.全合格 === false, "失败时 0/7、全合格 false", JSON.stringify({ 成: 果.成功, 全: 果.全合格 }));
    断言(果.行结果.length === 7 && 果.行结果.slice(0, 3).every((x) => /403/.test(x.插入报错)) && 果.行结果.slice(3).every((x) => /未发起/.test(x.插入报错)), "行结果：本批 3 行记 403 原文，后面 4 行记「未发起」", JSON.stringify(果.行结果.map((x) => x.插入报错.slice(0, 18))));
    const 证据体 = JSON.parse(fs.readFileSync(path.join(证据, "7-插图-批量-1.json"), "utf8"));
    断言(/403/.test(String(证据体.错误)), "失败批的证据文件带错误原文", String(证据体.错误).slice(0, 60));
    断言(!fs.existsSync(path.join(证据, "7-插图-批量-2.json")), "失败后不产生第 2 批证据");
  }

  console.log(`\n  结果：${通过} 通过 / ${失败} 失败\n`);
  process.exitCode = 失败 ? 1 : 0;
}

主().catch((错误) => {
  console.error(`\n  测试崩溃：${错误 && 错误.stack ? 错误.stack : 错误}\n`);
  process.exitCode = 1;
});
