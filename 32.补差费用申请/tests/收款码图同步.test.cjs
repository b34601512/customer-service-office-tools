#!/usr/bin/env node
// 32号 收款码图同步 回归测试（2026-10-08.7）：
//   ① 带图清单自动生成：批次 明细[].汇总行[2] 里的 =DISPIMG(…) → {源行,姓名,id,目标行}；
//      **没图的行不进清单**（手机号/银行卡/邮箱/空/普通文本都不算）；
//   ② 目标行映射：目标行 = 目标首行 + 明细序号（目标首行 = 预期末行.汇总 + 1，不硬编码偏移）；
//   ③ 行域拒写：超出批次行域 / 目标行重复 / 源行与批次矛盾 / 源行裸奔没批次 → 一律拒绝；
//   ④ 回读分拣：C 列还是批次里的源图 ID = 待插；换过 ID = 已插；#REF!/空/文本 = 待插（插图端会因非 DISPIMG 跳过）。
// 跑：node tests/收款码图同步.test.cjs
const fs = require("node:fs");
const path = require("node:path");

const 项目根 = path.resolve(__dirname, "..");
const { 解析DISPIMG, 从批次生成清单, 判定已插, 按回读分拣 } = require(path.join(项目根, "scripts", "收款码图清单.cjs"));
const { 规整插图文 } = require(path.join(项目根, "scripts", "写入在线表.cjs"));
const { 读批次 } = require(path.join(项目根, "scripts", "批次映射.cjs"));
const { 矩阵差异 } = require(path.join(项目根, "scripts", "同步收款码图.cjs"));

let 通过 = 0;
let 失败 = 0;
function 断言(条件, 说明, 实测 = "") {
  if (条件) { 通过 += 1; console.log(`  ✓ ${说明}`); }
  else { 失败 += 1; console.log(`  ✗ ${说明}${实测 ? `｜实测：${实测}` : ""}`); }
}
function 造明细(行号, 账号, 姓名) {
  const 汇总行 = new Array(18).fill("");
  汇总行[1] = 姓名;
  汇总行[2] = 账号;
  return { 源行号: 行号, 汇总行 };
}
function 造批次(明细, 预期汇总 = 1672) {
  return { 月份: "2026-09", 申请日期: "2026/10/8", 行数: 明细.length, 明细, 预期末行: { 汇总: 预期汇总, 集团: 19, 器械: 12 } };
}

function 主() {
  console.log("\n32号 收款码图同步 回归测试\n");

  // ── 1) 解析DISPIMG ───────────────────────────────────────────────────────────
  {
    断言(解析DISPIMG('=DISPIMG("ID_352FA1A825414A33B3C550B97EAE6B0C",1)') === "ID_352FA1A825414A33B3C550B97EAE6B0C", "解析DISPIMG(标准)");
    断言(解析DISPIMG('=dispimg( "ID_X" , 1 )') === "ID_X", "解析DISPIMG(大小写/空格)");
    断言(解析DISPIMG("6230880020019354729") === null, "解析DISPIMG(银行卡号) = null（没图）");
    断言(解析DISPIMG("15138007261") === null, "解析DISPIMG(手机号) = null（没图）");
    断言(解析DISPIMG("sstatjhking@126.com") === null, "解析DISPIMG(邮箱) = null（没图）");
    断言(解析DISPIMG("#REF!") === null, "解析DISPIMG(#REF!) = null");
    断言(解析DISPIMG("") === null && 解析DISPIMG(null) === null, "解析DISPIMG(空) = null");
  }

  // ── 2) 带图清单自动生成 + 没图的行不进清单 ───────────────────────────────────
  {
    const 明细 = [
      造明细(450, "6230880020019354729", "王家涛"),              // 银行卡 → 不进
      造明细(451, '=DISPIMG("ID_A",1)', "程小霞"),              // 图
      造明细(452, '=DISPIMG("ID_B",1)', "单佳"),
      造明细(453, '=DISPIMG("ID_C",1)', "姓黄"),
      造明细(454, '=DISPIMG("ID_D",1)', "顾雁婷"),
      造明细(455, "6217856300017063176", "胡兴"),                // 银行卡 → 不进
      造明细(456, '=DISPIMG("ID_E",1)', "谢燕"),
      造明细(457, "15138007261", "冯彩茹"),
      造明细(458, "13832492885", "马立山"),
      造明细(459, "sstatjhking@126.com", "林长利"),
      造明细(460, '=DISPIMG("ID_F",1)', "曾安清"),
      造明细(461, "13576687320", "曾涛"),
      造明细(462, '=DISPIMG("ID_G",1)', "韩雯")
    ];
    const 清单 = 从批次生成清单(造批次(明细));
    断言(清单.行数 === 13 && 清单.有图行数 === 7, "13 行批里挑出 7 行带图", JSON.stringify({ 行: 清单.行数, 图: 清单.有图行数 }));
    断言(清单.目标首行 === 1673 && 清单.目标末行 === 1685, "目标行域 1673~1685");
    const 源行们 = 清单.项.map((x) => x.源行).join(",");
    断言(源行们 === "451,452,453,454,456,460,462", "清单源行按明细顺序（没图行被跳过）", 源行们);
    const 目标们 = 清单.项.map((x) => x.目标行).join(",");
    断言(目标们 === "1674,1675,1676,1677,1679,1683,1685", "目标行 = 目标首行 + 明细序号（不硬编码偏移）", 目标们);
    断言(清单.项.every((x) => x.行 === x.源行), "每项保留 行=源行（导出工具的输入契约）");
    断言(清单.项[4].姓名 === "谢燕" && 清单.项[4].id === "ID_E", "姓名/ID 对应正确（谢燕→1679）", JSON.stringify(清单.项[4]));
    断言(!清单.项.some((x) => [450, 455, 457, 458, 459, 461].includes(x.源行)), "银行卡/手机号/邮箱行一个都不进清单");
  }

  // ── 3) 没图整批：清单为空，不抛错 ────────────────────────────────────────────
  {
    const 清单 = 从批次生成清单(造批次([造明细(470, "13800000000", "甲"), 造明细(471, "", "乙")]));
    断言(清单.有图行数 === 0 && 清单.项.length === 0, "整批没图 → 清单为空（同步脚本据此不启动浏览器）");
  }

  // ── 3b) 批次缺 预期末行/行数 → 抛错，不猜目标行 ──────────────────────────────
  {
    let 错 = "";
    try { 从批次生成清单({ 明细: [造明细(451, '=DISPIMG("ID_A",1)', "甲")] }); } catch (e) { 错 = e.message; }
    断言(/预期末行/.test(错), "缺 预期末行.汇总 → 抛错（拿不到目标首行）", 错);
  }

  // ── 4) 真批次回归：runtime/待写数据/2026-09.json（有快照才对账，没有就跳过）────
  {
    const 真实路径 = path.join(项目根, "runtime", "待写数据", "2026-09.json");
    const 手工路径 = path.join(项目根, "runtime", "收款码图", "2026-10-08", "清单.json");
    if (!fs.existsSync(真实路径)) {
      console.log("  - 跳过真批次对账：缺 runtime/待写数据/2026-09.json");
    } else {
      const 批次 = JSON.parse(fs.readFileSync(真实路径, "utf8"));
      const 清单 = 从批次生成清单(批次, { 文件: 真实路径 });
      断言(清单.有图行数 === 7, "真 9月批：自动挑出 7 行（= 当时手工清单）", String(清单.有图行数));
      const 目标们 = 清单.项.map((x) => x.目标行).join(",");
      断言(目标们 === "1674,1675,1676,1677,1679,1683,1685", "真 9月批：目标行 1674~1685 中那 7 行", 目标们);
      if (fs.existsSync(手工路径)) {
        const 手工 = JSON.parse(fs.readFileSync(手工路径, "utf8"));
        const 同 = 手工.length === 清单.项.length && 手工.every((m, i) => m.行 === 清单.项[i].源行 && m.姓名 === 清单.项[i].姓名 && m.id === 清单.项[i].id);
        断言(同, "真 9月批：自动清单 == 当时手工清单（源行/姓名/ID 全对）", JSON.stringify(清单.项.map((x) => [x.源行, x.姓名])));
      }
      const 批 = 读批次(批次);
      断言(批.源行到目标.get(451) === 1674 && 批.源行到目标.get(462) === 1685, "真 9月批：批次映射 451↔1674 / 462↔1685");
    }
  }

  // ── 5) 行域拒写（客户端 规整插图文，10-08 事故形态）──────────────────────────
  {
    const 批次 = 读批次(造批次([
      造明细(451, '=DISPIMG("ID_A",1)', "甲"),
      造明细(452, '=DISPIMG("ID_B",1)', "乙")
    ]));
    const 好图 = [{ 行: 1673, 目标行: 1673, 源行: 451, dataURL: "data:image/png;base64,AA" }];
    断言(规整插图文(好图, 批次).预期起 === 1673 && 规整插图文(好图, 批次).预期止 === 1674, "规整：批次行域 1673~1674");
    let 错1 = ""; try { 规整插图文([{ 行: 1677, 目标行: 1677, 源行: 451, dataURL: "data:image/png;base64,AA" }], 批次); } catch (e) { 错1 = e.message; }
    断言(/应写目标行/.test(错1) || /超出批次域/.test(错1), "行域拒写：目标行超出批次末行 → 拒绝", 错1);
    let 错2 = ""; try { 规整插图文([{ 行: 451, 源行: 451, dataURL: "data:image/png;base64,AA" }], null); } catch (e) { 错2 = e.message; }
    断言(/没给 --批次/.test(错2), "行域拒写：源行裸奔没批次 → 拒绝（10-08 事故根因）", 错2);
    let 错3 = ""; try {
      规整插图文([
        { 行: 1673, 目标行: 1673, 源行: 451, dataURL: "data:image/png;base64,AA" },
        { 行: 1673, 目标行: 1673, 源行: 451, dataURL: "data:image/png;base64,BB" }
      ], 批次);
    } catch (e) { 错3 = e.message; }
    断言(/重复/.test(错3), "行域拒写：目标行重复 → 拒绝", 错3);
  }

  // ── 6) 回读分拣：待插 / 已插 ─────────────────────────────────────────────────
  {
    const 清单 = { 项: [
      { 源行: 451, 姓名: "程小霞", id: "ID_SRC_A", 目标行: 1674 },
      { 源行: 452, 姓名: "单佳", id: "ID_SRC_B", 目标行: 1675 }
    ] };
    const 矩阵 = [];
    矩阵[1673] = ["", "", '=DISPIMG("ID_NEW_A",1)'];  // 1674 行：换过 ID → 已插
    矩阵[1674] = ["", "", '=DISPIMG("ID_SRC_B",1)'];  // 1675 行：还是源图 ID → 待插
    const 拣 = 按回读分拣(矩阵, 清单.项);
    断言(拣.已插.length === 1 && 拣.已插[0].目标行 === 1674, "分拣：换过图 ID → 已插（跳过，不重插）");
    断言(拣.待插.length === 1 && 拣.待插[0].目标行 === 1675, "分拣：还是批次源图 ID → 待插");
    断言(判定已插('=DISPIMG("ID_NEW",1)', "ID_SRC") === true && 判定已插('=DISPIMG("ID_SRC",1)', "ID_SRC") === false, "判定已插：严格按 当前ID≠源ID");
    断言(判定已插("#REF!", "ID_SRC") === false && 判定已插("", "ID_SRC") === false, "判定已插：#REF!/空 = 未插（插图端会按非 DISPIMG 跳过并报告）");
    let 错 = ""; try { 按回读分拣([], 清单.项); } catch (e) { 错 = e.message; }
    断言(/没有目标行/.test(错), "分拣：回读矩阵缺行 → 抛错停手（不猜）", 错);
  }

  // ── 7) 全表差异（回读前后对比）───────────────────────────────────────────────
  {
    const 前 = [[ "a", "b" ], [ "c" ]];
    const 后 = [[ "a", "b" ], [ "d" ]];
    const 差 = 矩阵差异(前, 后);
    断言(差.length === 1 && 差[0].行 === 2 && 差[0].列 === 1 && 差[0].前 === "c" && 差[0].后 === "d", "矩阵差异：只报真实变化的格", JSON.stringify(差));
    断言(矩阵差异(前, 前).length === 0, "矩阵差异：相同 → 0");
  }

  console.log(`\n  结果：${通过} 通过 / ${失败} 失败\n`);
  process.exitCode = 失败 ? 1 : 0;
}

主();
