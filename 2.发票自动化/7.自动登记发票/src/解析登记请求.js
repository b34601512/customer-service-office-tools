// 从客服消息文本里解析「发票登记请求」（纯函数，可单测）。
// 例：帮我登记这个订单的发票，店铺：拼多多2店；订单编号：260901-123456789012345；
//     发票信息：电子普票，发票抬头：某市示例艺术培训有限公司，企业税号：91330000XXXXXX1234
const { 是否个人票 } = require("./发票规则");

const 订单号模式 = /\b(\d{6}-\d{10,20})\b/;
const 全部标签 = [
  "店铺名称", "店铺", "订单编号", "订单号", "平台单号",
  "发票信息", "发票类型", "发票种类", "发票抬头", "抬头", "购买方名称",
  "企业税号", "纳税人识别号", "税号", "统一社会信用代码"
];

function 取值(文本, 标签列表) {
  for (const 标签 of 标签列表) {
    // 取值到「下一个标签 / 分隔符 / 行尾」为止：避免空格分隔时把后面的字段连读进来。
    const 停靠 = `(?=\\s*(?:${全部标签.join("|")})\\s*[:：]|[;；,，\\n]|$)`;
    const 正则 = new RegExp(标签 + "\\s*[:：]?\\s*(.+?)" + 停靠);
    const 命中 = 文本.match(正则);
    if (命中 && 命中[1].trim()) return 命中[1].trim();
  }
  return "";
}

function 解析登记请求(文本) {
  const 原文 = String(文本 || "").replace(/\r/g, "").replace(/\u3000/g, " ");
  const 店铺名 = 取值(原文, ["店铺名称", "店铺"]);
  let 订单号 = 取值(原文, ["订单编号", "订单号", "平台单号"]);
  if (!订单号) {
    const 命中 = 原文.match(订单号模式);
    if (命中) 订单号 = 命中[1];
  }
  const 发票类型 = 取值(原文, ["发票信息", "发票类型", "发票种类"]);
  const 抬头 = 取值(原文, ["发票抬头", "抬头", "购买方名称"]);
  const 税号 = 取值(原文, ["企业税号", "纳税人识别号", "税号", "统一社会信用代码"]);
  const 最终发票类型 = 发票类型 || "电子普票";
  // 个人票（2026-10-09 口径：只有开公司抬头的才填税号栏）：票种/发票信息里带「个人」→ 不因缺税号报缺项；
  // 生成写表数据 会把姓名写 AA、AB 留空。
  const 是个人票 = 是否个人票({ 发票类型: 最终发票类型 });
  const 缺项 = [];
  if (!店铺名) 缺项.push("店铺");
  if (!订单号) 缺项.push("订单号");
  if (!抬头) 缺项.push("发票抬头");
  if (!税号 && !是个人票) 缺项.push("税号");
  return {
    店铺名,
    订单号,
    发票类型: 最终发票类型,
    抬头,
    税号,
    是个人票,
    缺项,
    可处理: 缺项.length === 0
  };
}

module.exports = { 解析登记请求 };
