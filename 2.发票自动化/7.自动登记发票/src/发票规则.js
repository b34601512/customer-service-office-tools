// 发票登记规则（纯函数，可单测）——来源《6.4 咨询问题类型-发票问题》提炼稿。
// 硬规则：开票金额 = ERP 买家支付金额（平台支付金额/其他服务费不开）；只保留 2 位小数；
//        与平台「应开金额」必须一致，不一致要登记差额；赠品/搭配销售要拆分。

/** 四舍五入到 2 位小数（财务开票软件只能开两位）。 */
function 两位小数(数值) {
  return Math.round((Number(数值) + Number.EPSILON) * 100) / 100;
}

// 店铺 → 开票主体（来源：6.4 文档「主体与登记表」表）。店铺名支持中文名与内部代码两种写法。
const 主体匹配表 = [
  {
    主体: "德达医疗器械",
    匹配: [/pdd0?2/i, /pdd0?3/i, /pdd0?5/i, /tm0?1/i, /tm0?3/i, /jd0?8/i, /albb0?2/i, /dedakj/i, /抖音德达旗舰店/]
  },
  {
    主体: "德达医疗科技集团",
    匹配: [/pdd0?1/i, /pdd0?4/i, /tm0?2/i, /tm0?6/i, /tm0?8/i, /jd0?1/i, /jd0?2/i, /jd0?3/i, /jd0?6/i, /jd5s/i, /jd0?9/i, /albb0?1/i, /dy0?8/i, /有赞/i]
  }
];

/** 把中文店铺名归一化成内部代码风格，便于匹配（拼多多2店 → pdd02）。 */
function 归一化店铺名(店铺名) {
  const 名 = String(店铺名 || "").replace(/\s+/g, "");
  const 规则 = [
    [/拼多多0*(\d+)店?/g, (m, n) => "pdd" + String(n).padStart(2, "0")],
    [/天猫0*(\d+)店?/g, (m, n) => "tm" + String(n).padStart(2, "0")],
    [/京东0*(\d+)店?/g, (m, n) => "jd" + String(n).padStart(2, "0")],
    [/阿里(?:巴巴)?0*(\d+)店?/g, (m, n) => "albb" + String(n).padStart(2, "0")]
  ];
  let 结果 = 名;
  for (const [正则, 替换] of 规则) 结果 = 结果.replace(正则, 替换);
  return 结果;
}

/** 判定登记主体；判不出来返回空串（= 待人工确认）。 */
function 判定主体(店铺名) {
  const 归一 = 归一化店铺名(店铺名);
  for (const 条目 of 主体匹配表) {
    if (条目.匹配.some((正则) => 正则.test(归一))) return 条目.主体;
  }
  return "";
}

/**
 * 计算开票金额。
 * @param {{买家支付金额: number|string, 平台应开金额?: number|string}} 输入
 */
function 计算开票金额({ 买家支付金额, 平台应开金额 }) {
  const 买家 = 两位小数(买家支付金额);
  const 开票金额 = 买家; // 平台支付金额/其他服务费不开
  const 有平台金额 = 平台应开金额 !== undefined && 平台应开金额 !== null && String(平台应开金额) !== "";
  const 平台 = 有平台金额 ? 两位小数(平台应开金额) : null;
  const 差额 = 有平台金额 ? 两位小数(平台 - 开票金额) : null;
  return { 买家支付金额: 买家, 开票金额, 平台应开金额: 平台, 差额, 与平台一致: 差额 === 0 };
}

/** ERP 行里是不是赠品（ERP「赠品」列取值：是/不是）。 */
function 是赠品(行) {
  return String((行 && 行["赠品"]) || "").trim() === "是";
}

/**
 * 检查赠品 / 搭配销售拆分（规则：赠品按 0 登记但备注其销售金额；
 * 一个订单 ≥2 个非赠品产品且其中金额为 0 → 通知运营拆分）。
 * @param {Array<object>} 行列表 ERP 商品明细行
 */
function 检查赠品拆分(行列表) {
  const 行 = Array.isArray(行列表) ? 行列表 : [];
  const 赠品行 = 行.filter(是赠品);
  const 非赠品 = 行.filter((r) => !是赠品(r));
  const 提示 = [];
  const 金额取数 = (r) => Number(String(r["实际金额"] ?? r["让利后金额"] ?? "0").trim() || 0);
  const 零金额非赠品 = 非赠品.filter((r) => 金额取数(r) === 0);
  if (非赠品.length >= 2 && 零金额非赠品.length > 0) {
    提示.push("搭配销售：有产品金额为 0，需通知运营拆分并告知要拆分的金额");
  }
  if (赠品行.length > 0) {
    提示.push("含赠品：赠品金额按 0 登记，备注里要写明赠品销售金额（发票表格子表）");
  }
  return { 需拆分: 提示.length > 0, 提示, 赠品行数: 赠品行.length, 非赠品行数: 非赠品.length };
}

/** 判断 ERP 行是否已退款/作废（登记前要先查退款）。 */
function 检查退款作废(行列表) {
  const 行 = Array.isArray(行列表) ? 行列表 : [];
  const 已退款 = 行.some((r) => String(r["是否退款"] || "").trim() && String(r["是否退款"]).trim() !== "否");
  const 已作废 = 行.some((r) => {
    const 值 = String(r["作废"] || "").trim();
    return 值 && 值 !== "否" && 值 !== "未作废";
  });
  return { 已退款, 已作废, 可登记: !已退款 && !已作废 };
}

/**
 * 组装一条「待登记清单」条目。
 * @param {{请求: object, erp行: Array<object>, 平台应开金额?: number|string, 登记时间?: string}} 输入
 */
function 生成待登记条目({ 请求, erp行, 平台应开金额, 登记时间 }) {
  const 行 = Array.isArray(erp行) ? erp行 : [];
  const 首行 = 行[0] || {};
  const 金额 = 计算开票金额({ 买家支付金额: 首行["买家支付金额"], 平台应开金额 });
  const 拆分 = 检查赠品拆分(行);
  const 退款 = 检查退款作废(行);
  const 主体 = 判定主体(请求.店铺名);
  const 待人工 = [];
  if (!主体) 待人工.push("主体判不出来（店铺名不在映射表里）");
  if (!金额.与平台一致 && 金额.平台应开金额 !== null) {
    待人工.push(`ERP 与平台金额不一致：平台 ${金额.平台应开金额} / ERP ${金额.开票金额}，差额 ${金额.差额}，要登记差额明细`);
  }
  if (!退款.可登记) 待人工.push(退款.已退款 ? "该单 ERP 标记已退款，先核实" : "该单 ERP 标记已作废，先核实");
  if (拆分.需拆分) 待人工.push(...拆分.提示);
  return {
    登记时间: 登记时间 || new Date().toISOString(),
    主体,
    店铺: 请求.店铺名,
    订单号: 请求.订单号,
    单据编号: String(首行["单据编号"] || "").trim(),
    商品明细: 行.map((r) => ({
      商品名称: String(r["商品名称"] || "").trim(),
      规格名称: String(r["规格名称"] || "").trim(),
      订购数: String(r["订购数"] || "").trim(),
      实际金额: 两位小数(String(r["实际金额"] || "0").trim() || 0),
      赠品: 是赠品(r)
    })),
    开票金额: 金额.开票金额,
    平台应开金额: 金额.平台应开金额,
    金额差额: 金额.差额,
    发票类型: 请求.发票类型,
    抬头: 请求.抬头,
    税号: 请求.税号,
    付款时间: String(首行["付款时间"] || "").trim(),
    平台交易状态: String(首行["平台交易状态"] || "").trim(),
    待人工确认: 待人工,
    待人工完成: 待人工.length === 0
  };
}

/** 在已有待登记清单里按订单号查重（禁止重复登记 = 重复交税）。 */
function 查找重复登记(条目列表, 订单号) {
  const 号 = String(订单号 || "").trim();
  if (!号) return [];
  return (Array.isArray(条目列表) ? 条目列表 : []).filter((条目) => String((条目 && 条目.订单号) || "").trim() === 号);
}

module.exports = { 两位小数, 判定主体, 归一化店铺名, 计算开票金额, 检查赠品拆分, 检查退款作废, 生成待登记条目, 查找重复登记 };
