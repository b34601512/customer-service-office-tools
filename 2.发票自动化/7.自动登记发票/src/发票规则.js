// 发票登记规则（纯函数，可单测）——来源《6.4 咨询问题类型-发票问题》提炼稿。
// 硬规则：开票金额 = ERP 买家支付金额（平台支付金额/其他服务费不开）；只保留 2 位小数；
//        与平台「应开金额」必须一致，不一致要登记差额；赠品/搭配销售要拆分。

/** 四舍五入到 2 位小数（财务开票软件只能开两位）。 */
function 两位小数(数值) {
  return Math.round((Number(数值) + Number.EPSILON) * 100) / 100;
}

// 店铺 → 开票主体（来源：6.4 文档「主体与登记表」表）。店铺名支持中文名与内部代码两种写法。
const 主体匹配表 = [
  {
    主体: "德达医疗器械",
    匹配: [/pdd0?2/i, /pdd0?3/i, /pdd0?5/i, /tm0?1/i, /tm0?3/i, /jd0?8/i, /albb0?2/i, /dedakj/i, /抖音德达旗舰店/]
  },
  {
    主体: "德达医疗科技集团",
    匹配: [/pdd0?1/i, /pdd0?4/i, /tm0?2/i, /tm0?6/i, /tm0?8/i, /jd0?1/i, /jd0?2/i, /jd0?3/i, /jd0?6/i, /jd5s/i, /jd0?9/i, /albb0?1/i, /dy0?8/i, /有赞/i]
  }
];

/** 把中文店铺名归一化成内部代码风格，便于匹配（拼多多2店 → pdd02）。 */
function 归一化店铺名(店铺名) {
  const 名 = String(店铺名 || "").replace(/\s+/g, "");
  const 规则 = [
    [/拼多多0*(\d+)店?/g, (m, n) => "pdd" + String(n).padStart(2, "0")],
    [/天猫0*(\d+)店?/g, (m, n) => "tm" + String(n).padStart(2, "0")],
    [/京东0*(\d+)店?/g, (m, n) => "jd" + String(n).padStart(2, "0")],
    [/阿里(?:巴巴)?0*(\d+)店?/g, (m, n) => "albb" + String(n).padStart(2, "0")]
  ];
  let 结果 = 名;
  for (const [正则, 替换] of 规则) 结果 = 结果.replace(正则, 替换);
  return 结果;
}

/** 判定登记主体；判不出来返回空串（= 待人工确认）。 */
function 判定主体(店铺名) {
  const 归一 = 归一化店铺名(店铺名);
  for (const 条目 of 主体匹配表) {
    if (条目.匹配.some((正则) => 正则.test(归一))) return 条目.主体;
  }
  return "";
}

/**
 * 计算开票金额。
 * @param {{买家支付金额: number|string, 平台应开金额?: number|string}} 输入
 */
function 计算开票金额({ 买家支付金额, 平台应开金额 }) {
  const 买家 = 两位小数(买家支付金额);
  const 开票金额 = 买家; // 平台支付金额/其他服务费不开
  const 有平台金额 = 平台应开金额 !== undefined && 平台应开金额 !== null && String(平台应开金额) !== "";
  const 平台 = 有平台金额 ? 两位小数(平台应开金额) : null;
  const 差额 = 有平台金额 ? 两位小数(平台 - 开票金额) : null;
  return { 买家支付金额: 买家, 开票金额, 平台应开金额: 平台, 差额, 与平台一致: 差额 === 0 };
}

/** ERP 行里是不是赠品（ERP「赠品」列取值：是/不是）。 */
function 是赠品(行) {
  return String((行 && 行["赠品"]) || "").trim() === "是";
}

/** 日期 → Excel/WPS 序列号（1899-12-30 为 0 起算）：2025-01-01=45658、2026-09-28=46293。空/非法返回 null。 */
function 日期序列号(日期文本) {
  const 匹配 = String(日期文本 || "").match(/(\d{4})[-/年](\d{1,2})[-/月](\d{1,2})/);
  if (!匹配) return null;
  const 年 = Number(匹配[1]);
  const 月 = Number(匹配[2]);
  const 日 = Number(匹配[3]);
  const 毫秒 = Date.UTC(年, 月 - 1, 日) - Date.UTC(1899, 11, 30);
  return Math.round(毫秒 / 86400000);
}

/** 从 ERP 规格名称取登记表的型号：去掉括号里的容量/颜色/说明（含全角括号），再去空格。
 *  ERP `DH22-C1(9L)` → `DH22-C1`；`DE-1SW01 （9L）` → `DE-1SW01`；`鼻氧管-DEDAKJ（2米*透明）` → `鼻氧管-DEDAKJ`。
 *  型号在《德达医疗--产编》表里核对（型号列）。 */
function 提取型号(规格名称) {
  return String(规格名称 || "")
    .replace(/[（(][^）)]*[）)]/g, "")
    .replace(/\s+/g, "")
    .trim();
}

/** 登记表的店铺口径：拼多多2店 → 拼多多02店（天猫/京东不加 0）。 */
function 登记表店铺名(店铺名) {
  const 名 = String(店铺名 || "").replace(/\s+/g, "");
  const 拼多多 = 名.match(/^拼多多(\d+)店$/);
  if (拼多多) return "拼多多" + String(拼多多[1]).padStart(2, "0") + "店";
  return 名;
}

/** 登记表的票种口径：电子普票/普票 → 普票；专票/专用发票 → 专票。 */
function 登记表票种(发票类型) {
  const 文本 = String(发票类型 || "").trim();
  if (/专/.test(文本)) return "专票";
  if (/普/.test(文本)) return "普票";
  return 文本;
}

/**
 * 检查赠品 / 搭配销售拆分（规则：赠品按 0 登记但备注其销售金额；
 * 一个订单 ≥2 个非赠品产品且其中金额为 0 → 通知运营拆分）。
 * @param {Array<object>} 行列表 ERP 商品明细行
 */
function 检查赠品拆分(行列表) {
  const 行 = Array.isArray(行列表) ? 行列表 : [];
  const 赠品行 = 行.filter(是赠品);
  const 非赠品 = 行.filter((r) => !是赠品(r));
  const 提示 = [];
  const 金额取数 = (r) => Number(String(r["实际金额"] ?? r["让利后金额"] ?? "0").trim() || 0);
  const 零金额非赠品 = 非赠品.filter((r) => 金额取数(r) === 0);
  if (非赠品.length >= 2 && 零金额非赠品.length > 0) {
    提示.push("搭配销售：有产品金额为 0，需通知运营拆分并告知要拆分的金额");
  }
  if (赠品行.length > 0) {
    提示.push("含赠品：赠品金额按 0 登记，备注里要写明赠品销售金额（发票表格子表）");
  }
  return { 需拆分: 提示.length > 0, 提示, 赠品行数: 赠品行.length, 非赠品行数: 非赠品.length };
}

/** 判断 ERP 行是否已退款/作废（登记前要先查退款）。 */
function 检查退款作废(行列表) {
  const 行 = Array.isArray(行列表) ? 行列表 : [];
  const 已退款 = 行.some((r) => String(r["是否退款"] || "").trim() && String(r["是否退款"]).trim() !== "否");
  const 已作废 = 行.some((r) => {
    const 值 = String(r["作废"] || "").trim();
    return 值 && 值 !== "否" && 值 !== "未作废";
  });
  return { 已退款, 已作废, 可登记: !已退款 && !已作废 };
}

/**
 * 组装一条「待登记清单」条目。
 * @param {{请求: object, erp行: Array<object>, 平台应开金额?: number|string, 登记时间?: string}} 输入
 */
/**
 * 登记客服（表 O 列）：自动化登记的行必须写清楚是 AI 登的（用户 2026-09-28 拍板：写 AI 自己的名字）。
 * 不要写提需求客服的名字，否则事后追责时分不清是人登的还是自动登的。要改名就改这一个常量。
 */
const 登记客服名 = "木婉清";

function 生成待登记条目({ 请求, erp行, 平台应开金额, 登记时间, 登记客服 }) {
  const 行 = Array.isArray(erp行) ? erp行 : [];
  const 首行 = 行[0] || {};
  // 开票金额=整单「买家支付金额」之和（赠品行=0，不会重复计）。
  // 修因：原先只取首行，首行若是赠品（0）就把整单开票金额算成 0，差额被算成整笔平台金额。
  const 整单买家支付 = 行.reduce((和, r) => 和 + (Number(String(r["买家支付金额"] || "0").replace(/,/g, "").trim()) || 0), 0);
  const 金额 = 计算开票金额({ 买家支付金额: 整单买家支付, 平台应开金额 });
  // 开票金额覆盖（用户 2026-09-30 口径）：同一订单多次申请、有一笔已取消时按**未取消那笔**算。
  // ERP 的「买家支付金额」可能是已取消那笔的旧数，这时显式传 --开票金额 覆盖，并留下人工可见的说明。
  const 覆盖金额 = Number(String(请求.开票金额覆盖 ?? "").replace(/,/g, "").trim());
  const 已覆盖 = Number.isFinite(覆盖金额) && 覆盖金额 > 0 && 两位小数(覆盖金额) !== 金额.开票金额;
  if (已覆盖) {
    金额.开票金额 = 两位小数(覆盖金额);
    金额.差额 = 金额.平台应开金额 === null ? null : 两位小数(金额.平台应开金额 - 金额.开票金额);
    金额.与平台一致 = 金额.差额 === 0;
  }
  const 拆分 = 检查赠品拆分(行);
  const 退款 = 检查退款作废(行);
  const 主体 = 判定主体(请求.店铺名);
  const 待人工 = [];
  if (已覆盖) 待人工.push(`开票金额按「未取消那笔」覆盖为 ${金额.开票金额}（ERP 买家支付 ${两位小数(整单买家支付)} 是旧数，差额 ${金额.差额}）`);
  if (!主体) 待人工.push("主体判不出来（店铺名不在映射表里）");
  if (!金额.与平台一致 && 金额.平台应开金额 !== null) {
    待人工.push(`ERP 与平台金额不一致：平台 ${金额.平台应开金额} / ERP ${金额.开票金额}，差额 ${金额.差额}，要登记差额明细`);
  }
  if (!退款.可登记) 待人工.push(退款.已退款 ? "该单 ERP 标记已退款，先核实" : "该单 ERP 标记已作废，先核实");
  if (拆分.需拆分) 待人工.push(...拆分.提示);
  return {
    登记时间: 登记时间 || new Date().toISOString(),
    主体,
    店铺: 请求.店铺名,
    订单号: 请求.订单号,
    单据编号: String(首行["单据编号"] || "").trim(),
    商品明细: 行.map((r) => ({
      商品名称: String(r["商品名称"] || "").trim(),
      规格名称: String(r["规格名称"] || "").trim(),
      型号: 提取型号(r["规格名称"]),
      订购数: String(r["订购数"] || "").trim(),
      实际金额: 两位小数(String(r["实际金额"] || "0").trim() || 0),
      赠品: 是赠品(r)
    })),
    开票金额: 金额.开票金额,
    平台应开金额: 金额.平台应开金额,
    金额差额: 金额.差额,
    发票类型: 请求.发票类型,
    抬头: 请求.抬头,
    税号: 请求.税号,
    // 买家提供的开票资料（用户 2026-09-30：要登记齐全）——优先取入参，其次取 ERP 行上的发票字段
    注册地址: 请求.注册地址 || 首行["发票地址"] || "",
    注册电话: 请求.注册电话 || 首行["发票电话"] || "",
    开户银行: 请求.开户银行 || 首行["开户银行"] || "",
    开户账号: 请求.开户账号 || 首行["开户账号"] || "",
    收件手机号: 请求.收件手机号 || "",
    收件邮箱: 请求.收件邮箱 || "",
    收件人: 请求.收件人 || 首行["收货人"] || "",
    收件人电话: 请求.收件人电话 || 首行["收货人手机"] || "",
    收件人地址: 请求.收件人地址 || 首行["收货地址"] || "",
    付款时间: String(首行["付款时间"] || "").trim(),
    发货日期: (String(首行["发货时间"] || "").match(/\d{4}[-/]\d{1,2}[-/]\d{1,2}/) || [""])[0].replace(/\//g, "-"),
    平台交易状态: String(首行["平台交易状态"] || "").trim(),
    登记客服: String(登记客服 || 登记客服名).trim(),
    待人工确认: 待人工,
    待人工完成: 待人工.length === 0
  };
}

/**
 * 生成「写表数据」：待登记条目 → 登记表列字母 → 值（只包含我们该填的列；公式列一个都不出现）。
 * 列口径与来源见 `经验/登记表字段与数据来源.md`（2026-09-28 拿第 2751 行真实登记核对过）。
 * @param {object} 条目 生成待登记条目() 的产物
 * @param {{登记日期?: string}} [选项] 登记日期默认取条目.登记时间 的日期部分
 * @returns {{列: Record<string, {值: string|number, 类型: string}>, 待人工: string[]}}
 */
function 生成写表数据(条目, 选项 = {}) {
  const 项 = 条目 || {};
  const 待人工 = [];
  const 列 = {};
  // 明细序号 = 商品明细里的下标（0 = 主商品，也是默认；1/2… = 赠品那几行）。
  const 明细序号 = Number(选项.明细序号) || 0;
  const 全部明细 = 项.商品明细 || [];
  const 主明细列表 = 全部明细.filter((m) => !m.赠品);
  // 明细序号语义（用户 2026-09-30）：0 = 主商品；1/2… = 第几个赠品。
  // 修因：原实现 0 直接取 全部明细[0]，若 ERP 把赠品排在第一行（单 3316867933071006290 就是这样），
  //       主商品行会写成赠品的型号/数量、金额也会错位。
  const 赠品列表 = 全部明细.filter((m) => m.赠品);
  const 指定明细 = 明细序号 > 0 ? (赠品列表[明细序号 - 1] || null) : (主明细列表[0] || null);
  if (明细序号 > 0 && !指定明细) 待人工.push(`第 ${明细序号} 个赠品明细不存在（赠品共 ${赠品列表.length} 条）`);
  const 主明细 = 指定明细 || 主明细列表[0] || 全部明细[0] || {};
  const 是赠品行 = 明细序号 > 0;

  const 登记日期 = 选项.登记日期 || String(项.登记时间 || "").slice(0, 10);
  if (日期序列号(登记日期) === null) 待人工.push("登记日期取不到（A 列）");
  else 列["A"] = { 值: 日期序列号(登记日期), 类型: "日期序列号", 说明: 登记日期 };

  列["F"] = { 值: "正常", 类型: "文本" };

  const 票种 = 登记表票种(项.发票类型);
  if (票种) 列["G"] = { 值: 票种, 类型: "文本" };
  else 待人工.push("票种取不到（G 列）");

  if (项.店铺) 列["I"] = { 值: 登记表店铺名(项.店铺), 类型: "文本" };
  else 待人工.push("店铺取不到（I 列）");

  if (项.订单号) 列["J"] = { 值: String(项.订单号).trim(), 类型: "文本" };
  else 待人工.push("订单号取不到（J 列）");

  列["O"] = { 值: 项.登记客服 || 登记客服名, 类型: "文本" };

  const 型号 = 主明细.型号 || 提取型号(主明细.规格名称);
  if (型号) 列["U"] = { 值: 型号, 类型: "文本" };
  else 待人工.push("规格型号取不到（U 列）");

  const 数量 = Number(String(主明细.订购数 || "").trim());
  if (Number.isFinite(数量) && 数量 > 0) 列["V"] = { 值: 数量, 类型: "数字" };
  else 待人工.push("数量取不到（V 列）");

  if (是赠品行) {
    // 赠品金额 = 该行买家支付金额（通常 0）——用户 2026-09-30：赠品也要登记，金额为 0 元。
    const 赠品金额 = Number(String(主明细.买家支付金额 || "0").trim()) || 0;
    列["Y"] = { 值: 两位小数(赠品金额), 类型: "数字" };
  } else if (Number.isFinite(Number(项.开票金额))) 列["Y"] = { 值: 两位小数(项.开票金额), 类型: "数字" };
  else 待人工.push("开票金额取不到（Y 列）");

  if (项.抬头) 列["AA"] = { 值: String(项.抬头).trim(), 类型: "文本" };
  else 待人工.push("发票抬头取不到（AA 列）");
  if (项.税号) 列["AB"] = { 值: String(项.税号).trim(), 类型: "文本" };
  else 待人工.push("发票税号取不到（AB 列）");

  // 买家提供的开票资料（用户 2026-09-30：税号/抬头/银行/电话/地址都要登记齐全）。
  // 列口径：AC=注册地址 AD=注册电话 AE=开户银行 AF=开户账号 AG=收件手机号 AH=收件邮箱；
  //         P=收件人姓名 Q=收件人电话 R=收件人地址。只写买家真给了的，没给就不传键（不会抹空已有内容）。
  const 可选文本列 = [
    ["AC", 项.注册地址], ["AD", 项.注册电话], ["AE", 项.开户银行], ["AF", 项.开户账号],
    ["AG", 项.收件手机号], ["AH", 项.收件邮箱],
    ["P", 项.收件人], ["Q", 项.收件人电话], ["R", 项.收件人地址]
  ];
  for (const [字母, 值] of 可选文本列) {
    const 文本 = String(值 ?? "").trim();
    if (文本) 列[字母] = { 值: 文本, 类型: "文本" };
  }

  if (项.发货日期 && 日期序列号(项.发货日期) !== null) {
    列["AK"] = { 值: 日期序列号(项.发货日期), 类型: "日期序列号", 说明: 项.发货日期 };
  } else {
    待人工.push("发货日期取不到（AK 列，来源 ERP 发货时间）");
  }

  if (项.特殊要求) 列["S"] = { 值: String(项.特殊要求).trim(), 类型: "文本" };

  // 表②（集团）从 O 列起整体右移一列 —— 统一映射一次（表①不映射）。
  const 映射后 = {};
  for (const [字母, 项] of Object.entries(列)) 映射后[映射列字母(字母, 选项.表名)] = 项;
  return { 列: 映射后, 待人工 };
}

/** 列号(1起) → 列字母 */
function 列号转字母(列号) {
  let 序号 = Number(列号) || 0;
  let 字母 = "";
  while (序号 > 0) {
    const 余数 = ((序号 - 1) % 26) + 1;
    字母 = String.fromCharCode(64 + 余数) + 字母;
    序号 = Math.floor((序号 - 余数) / 26);
  }
  return 字母;
}

/** 列字母 → 列号(1起) */
function 字母转列号(字母) {
  let 列号 = 0;
  for (const 字符 of String(字母 || "").toUpperCase()) {
    const 值 = 字符.charCodeAt(0) - 64;
    if (值 < 1 || 值 > 26) return 0;
    列号 = 列号 * 26 + 值;
  }
  return 列号;
}

/**
 * 表列偏移：两张登记表的列位置不一样（2026-09-30 实测）。
 *   表①（德达医疗器械，子表「德达医疗器械发票登记 --毛叶红」）：O=客服、U=型号、V=数量、Y=金额、AA=抬头、AB=税号、AK=发货日期。
 *   表②（集团，子表「科技--唐雪梅」）：**从 O 列起整体右移一列** —— P=客服、V=型号、W=数量、Z=金额、AB=抬头、AC=税号、AL=发货日期。
 * 所以表②的列号 ≥ 15（O）的，统一 +1。
 */
function 表列偏移(表名) {
  const 名 = String(表名 || "");
  return /科技|集团/.test(名) ? 1 : 0;
}

/** 按表把列字母映射到目标表的列字母。 */
function 映射列字母(字母, 表名) {
  const 偏移 = 表列偏移(表名);
  if (!偏移) return 字母;
  const 列号 = 字母转列号(字母);
  if (列号 - 15 < 0) return 字母;
  return 列号转字母(列号 + 偏移);
}

/** 在已有待登记清单里按订单号查重（禁止重复登记 = 重复交税）。 */
function 查找重复登记(条目列表, 订单号) {
  const 号 = String(订单号 || "").trim();
  if (!号) return [];
  return (Array.isArray(条目列表) ? 条目列表 : []).filter((条目) => String((条目 && 条目.订单号) || "").trim() === 号);
}

