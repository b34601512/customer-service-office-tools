const test = require("node:test");
const assert = require("node:assert/strict");
const { 解析发票中心订单行 } = require("../src/拼多多发票中心");

// 实测页面正文片段（2026-09-28，拼多多02店发票中心，按订单号搜索后；抬头/税号已换成占位）
const 真实正文 = `订单开票
\t260901-123456789012345
\t已收货\t正常\t2026-09-28 14:30:26\t¥374.12\t手动\t电票\t蓝票\t企业\t某市示例艺术培训有限公司\t91330000XXXXXX1234\t-\t-\t2026-10-28 14:30:26
29天22时14分后逾期
\t录入发票
全选
批量自动开票
共有 1 条`;

test("真实页面：金额/抬头/税号/票种都解析出来", () => {
  const 结果 = 解析发票中心订单行(真实正文, "260901-123456789012345");
  assert.ok(结果);
  assert.equal(结果.金额, 374.12);
  assert.equal(结果.抬头, "某市示例艺术培训有限公司");
  assert.equal(结果.税号, "91330000XXXXXX1234");
  assert.equal(结果.票种, "电票");
  assert.equal(结果.发票颜色, "蓝票");
  assert.equal(结果.抬头类型, "企业");
  assert.equal(结果.申请时间, "2026-09-28 14:30:26");
  assert.equal(结果.承诺时间, "2026-10-28 14:30:26");
});

test("搜不到这单：返回 null，不瞎猜", () => {
  assert.equal(解析发票中心订单行("暂无数据", "260901-123456789012345"), null);
  assert.equal(解析发票中心订单行("", "x"), null);
});

test("金额带千分位也能解析", () => {
  const 正文 = `260901-123456789012345
\t已收货\t正常\t2026-09-28 14:30:26\t¥1,234.56\t手动\t电票\t蓝票\t企业\t某某公司\t91330000XXXXXX1234\t-\t-\t2026-10-28 14:30:26`;
  const 结果 = 解析发票中心订单行(正文, "260901-123456789012345");
  assert.equal(结果.金额, 1234.56);
});

test("空输入不崩", () => {
  assert.equal(解析发票中心订单行(null, "x"), null);
  assert.equal(解析发票中心订单行("x", ""), null);
});
