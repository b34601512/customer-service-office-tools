// ⑤ 老清单条目（没有逐行买家支付金额）遇到多主件：必须报缺金额、不许拿 0 静默凑数。
test("一单多主件⑤：老条目缺逐行买家支付金额 → 逐行报缺、无法对账、不静默写 0", () => {
  const 条目 = {
    订单号: "T-5", 店铺: "拼多多2店", 发票类型: "电子普票", 开票金额: 697.96,
    平台应开金额: 697.96, 抬头: "某某有限公司", 税号: "91330000XXXXXX1234",
    登记时间: "2026-10-08T10:00:00.000Z", 发货日期: "2026-10-04",
    商品明细: [
      { 规格名称: "纯正弦波逆变器", 型号: "纯正弦波逆变器", 订购数: "1", 实际金额: 134.7, 赠品: false },
      { 规格名称: "DH22-C1L(9L)", 型号: "DH22-C1L", 订购数: "1", 实际金额: 763.3, 赠品: false }
    ]
  };
  const 数据 = 生成写表数据(条目);
  assert.equal(数据.总行数, 2);
  for (const 行 of 数据.行列表) {
    assert.ok(行.待人工.some((t) => /买家支付金额/.test(t)), `行${行.行序号} 必须报缺金额`);
    assert.equal(行.列.Y, undefined, `行${行.行序号} 缺金额时不许写 0`);
  }
  assert.equal(数据.金额差额, null);
  assert.ok(数据.对账提示.some((t) => /无法/.test(t)));
});
