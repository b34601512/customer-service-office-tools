// 7号：一单多主件（组合/套装）单测 —— 2026-10-08 根因修复（现场：表① 2781 漏登记主机 DH22-C1L）。
// 规则：每条非赠品明细各出一行（主件按 ERP 顺序在前、赠品在后）；多主件时 Y=该行 ERP 买家支付金额
//       （=让利后金额）；赠品 Y=0；各行 Y 合计 ≠ 订单金额（平台金额优先）→ 返回 金额差额 + 对账提示，
//       不许静默凑数。单主件（含赠品）的老口径必须一字不变。
const test = require("node:test");
const assert = require("node:assert/strict");
const { 生成待登记条目, 生成写表数据 } = require("../src/发票规则");

// 写表只允许这些列；公式列（C/D/E/T/W/X/AO 等）一个都不许出现。
const 公式列 = ["C", "D", "E", "T", "W", "X", "AO", "AL", "AM", "AN"];
const 可写列 = new Set(["A", "F", "G", "I", "J", "O", "U", "V", "Y", "AA", "AB", "AC", "AD", "AE", "AF", "AG", "AH", "P", "Q", "R", "AK", "S"]);

function 断言行合法(行) {
  for (const 列 of Object.keys(行.列)) {
    assert.ok(可写列.has(列), `行${行.行序号} 出现不该写的列 ${列}`);
  }
  for (const 列 of 公式列) {
    assert.equal(行.列[列], undefined, `行${行.行序号} 公式列 ${列} 不该被写`);
  }
}

// ① 1 主件 + 1 赠品（现状必须不变）：ERP 里赠品排第一，输出仍主件在前、赠品在后。
test("一单多主件①：1 主件 + 1 赠品 → 2 行；主件 Y=整单开票金额（老口径），赠品 Y=0", () => {
  const 条目 = {
    订单号: "5127724117341157631", 店铺: "天猫6店", 发票类型: "增值税电子普通发票",
    开票金额: 499, 抬头: "天虹数科商业股份有限公司", 税号: "91440300618842912J",
    登记时间: "2026-10-08T10:00:00.000Z", 发货日期: "2026-10-04",
    商品明细: [
      { 规格名称: "氧气袋(DEDAKJ）", 型号: "YQD-DK", 订购数: "1", 买家支付金额: 0, 赠品: true },
      { 规格名称: "家用制氧机DH21-A1L（LV）DEDAKJ", 型号: "DH21-A1L", 订购数: "1", 买家支付金额: 499, 赠品: false }
    ]
  };
  const 数据 = 生成写表数据(条目);
  assert.equal(数据.总行数, 2);
  assert.equal(数据.多主件, false);
  assert.deepEqual(数据.行列表.map((r) => r.行序号), [1, 2]);
  assert.deepEqual(数据.行列表.map((r) => r.是否主行), [true, false]);

  const [主, 赠] = 数据.行列表;
  assert.equal(主.列.U.值, "DH21-A1L");
  assert.equal(主.列.V.值, 1);
  assert.equal(主.列.Y.值, 499); // 单主件老口径：Y=开票金额
  assert.equal(赠.列.U.值, "YQD");
  assert.equal(赠.列.Y.值, 0);
  // 默认选中的还是第 1 行（主件）——旧调用不变
  assert.equal(数据.列.U.值, "DH21-A1L");
  assert.equal(数据.列.Y.值, 499);
  // 老口径 明细序号=1 仍取第 1 个赠品
  assert.equal(生成写表数据(条目, { 明细序号: 1 }).列.U.值, "YQD");
  // 最小可写列集合：单主件的列与 2026-09-28 真行核对过的一模一样
  assert.equal(Object.keys(主.列).sort().join(","), "A,AA,AB,AK,F,G,I,J,O,U,V,Y");
  // 金额对账：499 + 0 = 499，无差额
  assert.equal(数据.金额差额, 0);
  assert.deepEqual(数据.对账提示, []);
  for (const 行 of 数据.行列表) 断言行合法(行);
});

// ② 2 主件（本单形态）：ERP 顺序保留（逆变器 104.70 在前、主机 DH22-C1L 593.30 在后）；
//    平台 697.96 / ERP 行合计 698.00，差 0.04 必须报差额、不静默。
test("一单多主件②：2 主件各行 Y=该行买家支付；与平台 697.96 差 0.04 → 报差额、不静默凑数", () => {
  const 条目 = 生成待登记条目({
    请求: {
      店铺名: "拼多多2店", 订单号: "260926-***********0863", 发票类型: "电子普票",
      抬头: "青岛元胜堂医疗管理有限公司", 税号: "91370203MAE2TXW57X",
      开票金额覆盖: "697.96", 开票金额覆盖说明: "按平台后台金额为准（黎路遥 2026-10-06 15:39）"
    },
    平台应开金额: "697.96",
    erp行: [
      {
        店铺名称: "德达医疗旗舰店", 单据编号: "SO1023113971098", 商品名称: "6.03.27.000003",
        规格名称: "纯正弦波逆变器", 订购数: "1.0000", 实际金额: "134.7000", 让利后金额: "104.7000",
        让利金额: "30.0000", 买家支付金额: "104.7000", 赠品: "不是", 作废: "否",
        发货时间: "2026-09-26 14:45:15", 平台交易状态: "已发货待签收"
      },
      {
        店铺名称: "德达医疗旗舰店", 单据编号: "SO1023113971098", 商品名称: "8.01.1.01.01.234",
        规格名称: "DH22-C1L(9L)", 订购数: "1.0000", 实际金额: "763.3000", 让利后金额: "593.3000",
        让利金额: "170.0000", 买家支付金额: "593.3000", 赠品: "不是", 作废: "否",
        发货时间: "2026-09-26 14:45:15", 平台交易状态: "已发货待签收"
      }
    ],
    登记时间: "2026-10-08T10:00:00.000Z"
  });
  // 待登记条目要带上每行的买家支付/让利后金额（否则多主件拆不出来）
  assert.equal(条目.商品明细[0].买家支付金额, 104.7);
  assert.equal(条目.商品明细[1].买家支付金额, 593.3);
  assert.equal(条目.商品明细[0].让利后金额, 104.7);
  assert.equal(条目.商品明细[1].让利后金额, 593.3);

  const 数据 = 生成写表数据(条目);
  assert.equal(数据.总行数, 2);
  assert.equal(数据.多主件, true);
  assert.deepEqual(数据.行列表.map((r) => r.列.U.值), ["纯正弦波逆变器", "DH22-C1L"]); // ERP 顺序
  assert.deepEqual(数据.行列表.map((r) => r.列.V.值), [1, 1]);
  assert.deepEqual(数据.行列表.map((r) => Number(r.列.Y.值)), [104.7, 593.3]);
  assert.deepEqual(数据.行列表.map((r) => r.是否主行), [true, true]);

  // 对账：基准=平台 697.96，各行合计 698.00 → 差额 -0.04（照现有口径：平台 − 开票）
  assert.equal(数据.对账基准, 697.96);
  assert.equal(数据.金额差额, -0.04);
  assert.ok(数据.对账提示.length > 0, "差额≠0 必须有提示");
  assert.match(数据.对账提示.join("；"), /差额/);
  assert.match(数据.对账提示.join("；"), /698/);
  assert.deepEqual(数据.待人工, [], "差额走「对账提示」由上层决定，不塞进字段缺项闸门");
  for (const 行 of 数据.行列表) 断言行合法(行);

  // 行序号选行：第 2 行 = 主机 DH22-C1L / 593.30；越界必须报待人工
  const 第二行 = 生成写表数据(条目, { 行序号: 2 });
  assert.equal(第二行.列.U.值, "DH22-C1L");
  assert.equal(Number(第二行.列.Y.值), 593.3);
  const 越界 = 生成写表数据(条目, { 行序号: 9 });
  assert.ok(越界.待人工.some((t) => /第 9 行不存在/.test(t)));
});

// ③ 2 主件 + 1 赠品：主件按 ERP 顺序（含中间夹着赠品的 ERP 排布）、赠品排最后。
test("一单多主件③：2 主件 + 1 赠品 → 3 行；主件按 ERP 顺序、赠品在后；行序号可选任意行", () => {
  const 条目 = {
    订单号: "T-3", 店铺: "拼多多2店", 发票类型: "电子普票", 开票金额: 500,
    抬头: "某某有限公司", 税号: "91330000XXXXXX1234",
    登记时间: "2026-10-08T10:00:00.000Z", 发货日期: "2026-10-04",
    商品明细: [
      { 规格名称: "制氧机DH22-C1(9L)", 型号: "DH22-C1", 订购数: "1", 买家支付金额: 300, 赠品: false },
      { 规格名称: "氧气袋(DEDAKJ）", 型号: "YQD-DK", 订购数: "1", 买家支付金额: 0, 赠品: true },
      { 规格名称: "纯正弦波逆变器", 型号: "纯正弦波逆变器", 订购数: "2", 买家支付金额: 200, 赠品: false }
    ]
  };
  const 数据 = 生成写表数据(条目);
  assert.equal(数据.总行数, 3);
  assert.deepEqual(数据.行列表.map((r) => r.行序号), [1, 2, 3]);
  assert.deepEqual(数据.行列表.map((r) => r.是否主行), [true, true, false]);
  assert.deepEqual(数据.行列表.map((r) => r.列.U.值), ["DH22-C1", "纯正弦波逆变器", "YQD"]);
  assert.deepEqual(数据.行列表.map((r) => r.列.V.值), [1, 2, 1]);
  assert.deepEqual(数据.行列表.map((r) => Number(r.列.Y.值)), [300, 200, 0]);
  assert.equal(数据.金额差额, 0); // 300+200+0 = 500

  // 行序号（1 起）按全量行列表选：2=第 2 条主件，3=赠品；老口径 明细序号=1 也取赠品
  assert.equal(生成写表数据(条目, { 行序号: 2 }).列.U.值, "纯正弦波逆变器");
  assert.equal(生成写表数据(条目, { 行序号: 3 }).列.U.值, "YQD");
  assert.equal(Number(生成写表数据(条目, { 行序号: 3 }).列.Y.值), 0);
  assert.equal(生成写表数据(条目, { 明细序号: 1 }).列.U.值, "YQD");
  for (const 行 of 数据.行列表) 断言行合法(行);
});

// ④ 单主件：只有 1 行，Y 照旧=开票金额（含平台覆盖），金额对账 0 差额。
