const test = require("node:test");
const assert = require("node:assert/strict");
const {
  两位小数,
  判定主体,
  归一化店铺名,
  计算开票金额,
  检查赠品拆分,
  检查退款作废,
  生成待登记条目
} = require("../src/发票规则");

test("两位小数：四舍五入到分", () => {
  assert.equal(两位小数(374.123), 374.12);
  assert.equal(两位小数(374.125), 374.13);
  assert.equal(两位小数("374.1"), 374.1);
  assert.equal(两位小数(0), 0);
});

test("店铺归一化与主体判定", () => {
  assert.equal(归一化店铺名("拼多多2店"), "pdd02");
  assert.equal(归一化店铺名("拼多多03店"), "pdd03");
  assert.equal(判定主体("拼多多2店"), "德达医疗器械");
  assert.equal(判定主体("拼多多03店"), "德达医疗器械");
  assert.equal(判定主体("天猫02店"), "德达医疗科技集团");
  assert.equal(判定主体("京东08店"), "德达医疗器械");
  assert.equal(判定主体("没见过的店"), "");
});

test("开票金额=买家支付金额，平台支付/服务费不开", () => {
  const 结果 = 计算开票金额({ 买家支付金额: 374.12, 平台应开金额: 374.12 });
  assert.equal(结果.开票金额, 374.12);
  assert.equal(结果.与平台一致, true);
  assert.equal(结果.差额, 0);
});

test("与平台金额不一致：登记差额", () => {
  const 结果 = 计算开票金额({ 买家支付金额: 374.12, 平台应开金额: 375 });
  assert.equal(结果.与平台一致, false);
  assert.equal(结果.差额, 0.88);
});

test("没给平台金额：不算差额，不瞎判一致", () => {
  const 结果 = 计算开票金额({ 买家支付金额: 100 });
  assert.equal(结果.平台应开金额, null);
  assert.equal(结果.差额, null);
  assert.equal(结果.与平台一致, false);
});

test("赠品拆分：赠品要备注销售金额", () => {
  const 结果 = 检查赠品拆分([
    { 赠品: "不是", 实际金额: "374.12" },
    { 赠品: "是", 实际金额: "0" }
  ]);
  assert.equal(结果.需拆分, true);
  assert.equal(结果.赠品行数, 1);
  assert.match(结果.提示.join(" "), /赠品/);
});

test("搭配销售：≥2 个非赠品且其中一个 0 金额 → 要通知运营拆分", () => {
  const 结果 = 检查赠品拆分([
    { 赠品: "不是", 实际金额: "374.12" },
    { 赠品: "不是", 实际金额: "0" }
  ]);
  assert.equal(结果.需拆分, true);
  assert.match(结果.提示.join(" "), /搭配销售/);
});

test("单产品无赠品：不需要拆分", () => {
  const 结果 = 检查赠品拆分([{ 赠品: "不是", 实际金额: "374.12" }]);
  assert.equal(结果.需拆分, false);
  assert.deepEqual(结果.提示, []);
});

test("退款/作废检查：已退款或已作废都不能直接登记", () => {
  assert.equal(检查退款作废([{ 是否退款: "否", 作废: "否" }]).可登记, true);
  assert.equal(检查退款作废([{ 是否退款: "是", 作废: "否" }]).可登记, false);
  assert.equal(检查退款作废([{ 是否退款: "", 作废: "是" }]).可登记, false);
});

test("生成待登记条目：真实场景（拼多多2店 374.12 电子普票）", () => {
  const 条目 = 生成待登记条目({
    请求: {
      店铺名: "拼多多2店",
      订单号: "260901-123456789012345",
      发票类型: "电子普票",
      抬头: "某市示例艺术培训有限公司",
      税号: "91330000XXXXXX1234"
    },
    平台应开金额: "374.12",
    erp行: [
      {
        店铺名称: "德达医疗旗舰店",
        单据编号: "SO0000000000000",
        平台单号: "260901-123456789012345",
        付款时间: "2026-09-03 00:46:53",
        商品名称: "8.01.1.01.01.233",
        规格名称: "DH22-C1(9L)",
        订购数: "1.0000",
        实际金额: "598.0000",
        买家支付金额: "374.12",
        平台支付金额: "23.88",
        赠品: "不是",
        作废: "否",
        平台交易状态: "已发货待签收"
      }
    ]
  });
  assert.equal(条目.主体, "德达医疗器械");
  assert.equal(条目.开票金额, 374.12);
  assert.equal(条目.金额差额, 0);
  assert.equal(条目.单据编号, "SO0000000000000");
  assert.equal(条目.商品明细.length, 1);
  assert.equal(条目.商品明细[0].规格名称, "DH22-C1(9L)");
  assert.deepEqual(条目.待人工确认, []);
  assert.equal(条目.待人工完成, true);
  // 表 O 列「登记客服」必须写 AI 自己的名字（用户 2026-09-28 拍板），不能拿提需求客服的名字充数
  assert.equal(条目.登记客服, "AI助手");
  assert.equal(生成待登记条目({ 请求: {}, erp行: [], 登记客服: "别人" }).登记客服, "别人");
});

test("生成待登记条目：金额对不上/已退款时挂待人工", () => {
  const 条目 = 生成待登记条目({
    请求: { 店铺名: "拼多多2店", 订单号: "260901-1", 发票类型: "电子普票", 抬头: "X", 税号: "Y" },
    平台应开金额: 375,
    erp行: [{ 买家支付金额: "374.12", 是否退款: "是", 赠品: "不是", 实际金额: "374.12" }]
  });
  const 文本 = 条目.待人工确认.join("；");
  assert.match(文本, /差额/);
  assert.match(文本, /退款/);
  assert.equal(条目.待人工完成, false);
});

test("查重：同一订单号只认已有条目（禁止重复登记）", () => {
  const { 查找重复登记 } = require("../src/发票规则");
  const 清单 = [{ 订单号: "A-1" }, { 订单号: "B-2" }, { 订单号: "A-1" }];
  assert.equal(查找重复登记(清单, "A-1").length, 2);
  assert.equal(查找重复登记(清单, "C-3").length, 0);
  assert.equal(查找重复登记(清单, "").length, 0);
  assert.equal(查找重复登记(null, "A-1").length, 0);
});
