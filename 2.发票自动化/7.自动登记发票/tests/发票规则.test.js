test("生成写表数据：与客服真实登记行（第 2751 行）逐列对齐，且公式列一个都不写", () => {
  const { 生成待登记条目, 生成写表数据 } = require("../src/发票规则");
  const 条目 = 生成待登记条目({
    请求: {
      店铺名: "拼多多2店",
      订单号: "260903-171347832413939",
      发票类型: "电子普票",
      抬头: "某市示例艺术培训有限公司",
      税号: "91330000XXXXXX1234"
    },
    平台应开金额: "374.12",
    erp行: [
      {
        单据编号: "SO0000000000000",
        规格名称: "DH22-C1(9L)",
        订购数: "1.0000",
        买家支付金额: "374.12",
        平台支付金额: "23.88",
        发货时间: "2026-09-03 08:35:59",
        赠品: "不是",
        作废: "否"
      }
    ],
    登记时间: "2026-09-28T10:00:00.000Z"
  });
  const { 列, 待人工 } = 生成写表数据(条目);
  assert.deepEqual(待人工, []);
  assert.equal(列.A.值, 46293); // 2026-09-28
  assert.equal(列.F.值, "正常");
  assert.equal(列.G.值, "普票");
  assert.equal(列.I.值, "拼多多02店");
  assert.equal(列.J.值, "260903-171347832413939");
  assert.equal(列.O.值, "AI助手");
  assert.equal(列.U.值, "DH22-C1");
  assert.equal(列.V.值, 1);
  assert.equal(列.Y.值, 374.12);
  assert.equal(列.AA.值, "某市示例艺术培训有限公司");
  assert.equal(列.AB.值, "91330000XXXXXX1234");
  assert.equal(列.AK.值, 46268); // 2026-09-03（用户拍板：按 ERP 口径，几天差异无所谓）
  // 反向断言：公式列永远不能出现在写表数据里（写进去会被覆盖/报错）
  for (const 公式列 of ["C", "D", "E", "T", "W", "X", "AO", "AL", "AM", "AN"]) {
    assert.equal(列[公式列], undefined, `公式列 ${公式列} 不该被写`);
  }
});

