const test = require("node:test");
const assert = require("node:assert/strict");
const { 解析登记请求 } = require("../src/解析登记请求");

const 真实消息 = "帮我登记这个订单的发票，店铺：拼多多2店；订单编号：260901-123456789012345；发票信息：电子普票，发票抬头：某市示例艺术培训有限公司，企业税号：91330000XXXXXX1234";

test("真实消息：字段全部解析出来", () => {
  const 请求 = 解析登记请求(真实消息);
  assert.equal(请求.店铺名, "拼多多2店");
  assert.equal(请求.订单号, "260901-123456789012345");
  assert.equal(请求.发票类型, "电子普票");
  assert.equal(请求.抬头, "某市示例艺术培训有限公司");
  assert.equal(请求.税号, "91330000XXXXXX1234");
  assert.deepEqual(请求.缺项, []);
  assert.equal(请求.可处理, true);
});

test("别名标签：订单号/抬头/纳税人识别号也能认", () => {
  const 请求 = 解析登记请求("订单号:123456-1234567890123 抬头：某某有限公司 纳税人识别号：91330000XXXXXX1234");
  assert.equal(请求.订单号, "123456-1234567890123");
  assert.equal(请求.抬头, "某某有限公司");
  assert.equal(请求.税号, "91330000XXXXXX1234");
});

test("没有标签的订单号：也能从正文里捞出来", () => {
  const 请求 = 解析登记请求("麻烦开下发票 260901-123456789012345 谢谢");
  assert.equal(请求.订单号, "260901-123456789012345");
});

test("缺项：缺什么报什么，不许瞎猜", () => {
  const 请求 = 解析登记请求("帮我登记发票，店铺：拼多多2店");
  assert.equal(请求.可处理, false);
  assert.deepEqual(请求.缺项, ["订单号", "发票抬头", "税号"]);
});

test("发票类型缺省：默认电子普票", () => {
  const 请求 = 解析登记请求("店铺：拼多多2店；订单编号：260901-123456789012345；发票抬头：某某公司；企业税号：91330000XXXXXX1234");
  assert.equal(请求.发票类型, "电子普票");
});

test("全角冒号与多余空格都能处理", () => {
  const 请求 = 解析登记请求("店铺 ： 拼多多2店 ；订单编号 ： 260901-123456789012345 ；发票抬头 ： 某某公司 ；企业税号 ： 91330000XXXXXX1234");
  assert.equal(请求.店铺名, "拼多多2店");
  assert.equal(请求.抬头, "某某公司");
});

test("空输入不崩", () => {
  const 请求 = 解析登记请求("");
  assert.equal(请求.可处理, false);
  assert.equal(请求.订单号, "");
});

// 个人票（2026-10-09 口径更正：只有开公司抬头的才填税号栏；姓名写 AA、AB 留空）：
// 票种/发票信息里带「个人」→ 无税号也不再报缺项；企业票维持原样。
test("个人票：票种带「个人」且无税号 → 不报税号缺项", () => {
  const 请求 = 解析登记请求("店铺：天猫2店；订单编号：3316468010210055174；发票信息：增值税电子普通发票 - 个人；发票抬头：曹县和顺园1号楼二单元李锦民");
  assert.equal(请求.税号, "");
  assert.equal(请求.是个人票, true);
  assert.deepEqual(请求.缺项, []);
  assert.equal(请求.可处理, true);
});

test("企业票仍必须税号（反向断言）", () => {
  const 请求 = 解析登记请求("店铺：天猫2店；订单编号：3316468010210055174；发票信息：增值税电子普通发票；发票抬头：某某有限公司");
  assert.equal(请求.是个人票, false);
  assert.deepEqual(请求.缺项, ["税号"]);
  assert.equal(请求.可处理, false);
});
