const { 规范化文本 } = require('./normalizeRecord');

function 取记录合并文本(记录 = {}) {
  // 解决：把不同来源的记录字段统一成可判断状态的文本。
  const 字段文本 = 记录.fields && typeof 记录.fields === 'object'
    ? Object.values(记录.fields).join(' | ')
    : Object.values(记录).join(' | ');
  return `${记录.summary || ''} | ${字段文本}`;
}

function 取发票上传倒计时文本(记录 = {}) {
  // 解决：优先读取明细表的倒计时字段，只有这个字段明确写“未逾期”才算已上传合格。
  const 字段来源列表 = [
    记录,
    记录.fields && typeof 记录.fields === 'object' ? 记录.fields : {},
  ];

  for (const 字段来源 of 字段来源列表) {
    const 命中键 = Object.keys(字段来源).find((键) => /发票上传.*倒计时/.test(键) && !/开始时间/.test(键));
    if (命中键) {
      return 规范化文本(字段来源[命中键]);
    }
  }

  return '';
}

function 识别开票明细状态(记录 = {}) {
  // 解决：从京东明细行里识别订单是否还需要登记开票，避免已上传订单继续报警。
  const 合并文本 = 取记录合并文本(记录);
  const 倒计时文本 = 取发票上传倒计时文本(记录);
  const 判断文本 = 倒计时文本 || 合并文本;

  if (倒计时文本 === '未逾期') {
    return {
      状态: '已上传未逾期',
      需要登记: false,
      需要预警: false,
    };
  }

  if (/已逾期|超期/.test(判断文本)) {
    return {
      状态: '待登记已逾期',
      需要登记: true,
      需要预警: true,
    };
  }

  const 距离逾期天数 = 识别距离逾期天数(判断文本);
  if (距离逾期天数 !== null) {
    return {
      状态: 距离逾期天数 <= 5 ? '待登记即将逾期' : '待登记未到预警期',
      需要登记: true,
      需要预警: 距离逾期天数 <= 5,
    };
  }

  if (/即将逾期|剩余处理时间不足\s*5\s*天/.test(判断文本)) {
    return {
      状态: '待登记即将逾期',
      需要登记: true,
      需要预警: true,
    };
  }

  if (!倒计时文本 && /(^|[；|:\s])未逾期($|[；|:\s])/.test(合并文本)) {
    return {
      状态: '已上传未逾期',
      需要登记: false,
      需要预警: false,
    };
  }

  if (/待处理|待登记|去开票/.test(合并文本)) {
    return {
      状态: '待登记待确认',
      需要登记: true,
      需要预警: false,
    };
  }

  return {
    状态: '已记录待确认',
    需要登记: false,
    需要预警: false,
  };
}

function 识别距离逾期天数(文本 = '') {
  // 解决：把“还有 8 天逾期”和“还有 3 天逾期”拆开，前者要提醒登记但不是最后预警。
  const 匹配结果 = String(文本 || '').match(/还有\s*(\d+)\s*天逾期/);
  if (!匹配结果) {
    return null;
  }

  return Number(匹配结果[1]);
}

function 补充开票明细状态(原始记录 = {}) {
  // 解决：把状态写入记录字段，后续报告和后台卡片都能看到判断依据。
  const 明细状态 = 识别开票明细状态(原始记录);
  return {
    ...原始记录,
    巡检状态: 明细状态.状态,
  };
}

function 统计开票明细状态(记录列表 = [], 原始指标 = {}) {
  // 解决：报警以“应上传-及时上传”为源头，顶部 5 天预警只作为紧急程度参考。
  const 记录数组 = Array.isArray(记录列表) ? 记录列表 : [];
  const 明细状态列表 = 记录数组.map((记录) => 识别开票明细状态(记录));
  const 待登记状态数 = 明细状态列表.filter((状态) => 状态.需要登记).length;
  const 已上传未逾期数 = 明细状态列表.filter((状态) => 状态.状态 === '已上传未逾期').length;
  const 预警明细数 = 明细状态列表.filter((状态) => 状态.需要预警).length;
  const 页面警告订单数 = 取非负整数(
    有指标字段(原始指标, '页面警告订单数') ? 原始指标.页面警告订单数 : 原始指标?.警告订单数,
  );
  const 明细总数 = 取非负整数(原始指标?.明细总数);
  const 顶部警告已识别 = Boolean(原始指标?.顶部警告已识别);
  const 上传指标已识别 = 是否已识别上传指标(原始指标);
  const 待上传发票订单数 = 上传指标已识别 ? 计算待上传发票订单数(原始指标) : 0;
  const 有效警告订单数 = 上传指标已识别
    ? 待上传发票订单数
    : Math.max(页面警告订单数, 预警明细数);
  const 待登记明细数 = 上传指标已识别
    ? 待上传发票订单数
    : Math.max(待登记状态数, 有效警告订单数);

  return {
    顶部警告已识别,
    页面警告订单数,
    有效警告订单数,
    明细总数,
    及时上传发票订单数: 取非负整数(原始指标?.及时上传发票订单数),
    应上传发票订单数: 取非负整数(原始指标?.应上传发票订单数),
    上传指标已识别,
    待上传发票订单数,
    待登记明细数,
    已上传未逾期数,
  };
}

function 有指标字段(指标 = {}, 字段名) {
  // 解决：区分“页面明确给 0”和“字段不存在”，避免 0 被当成无数据。
  return Object.prototype.hasOwnProperty.call(指标 || {}, 字段名);
}

function 是否已识别上传指标(指标 = {}) {
  // 解决：只有同时拿到应上传和及时上传，才使用核心差额覆盖旧预警逻辑。
  if (有指标字段(指标, '上传指标已识别')) {
    return 指标.上传指标已识别 === true;
  }

  return 有指标字段(指标, '应上传发票订单数') && 有指标字段(指标, '及时上传发票订单数');
}

function 计算待上传发票订单数(指标 = {}) {
  // 解决：统一落实“应上传发票订单数 - 及时上传发票订单数 > 0”的报警规则。
  if (有指标字段(指标, '待上传发票订单数')) {
    return 取非负整数(指标.待上传发票订单数);
  }

  return Math.max(
    取非负整数(指标?.应上传发票订单数) - 取非负整数(指标?.及时上传发票订单数),
    0,
  );
}

function 取非负整数(值) {
  // 解决：把页面数量字段统一为非负整数，避免 NaN 污染巡检指标。
  const 数字 = Number(值);
  if (!Number.isFinite(数字) || 数字 <= 0) {
    return 0;
  }

  return Math.floor(数字);
}

function 筛选需要登记的开票记录(记录列表 = []) {
  // 解决：通知和报告只针对真正需要处理的订单，已上传未逾期记录只留档。
  return (Array.isArray(记录列表) ? 记录列表 : [])
    .filter((记录) => 识别开票明细状态(记录).需要登记);
}

module.exports = {
  识别开票明细状态,
  补充开票明细状态,
  统计开票明细状态,
  筛选需要登记的开票记录,
};
