function 从页面文本提取开票指标(页面文本 = '') {
  // 解决：从核心指标、顶部预警和明细分页文案里提取数量，避免 DOM 结构变化导致漏报。
  const 规范文本 = String(页面文本 ?? '')
    .replace(/\u00a0/g, ' ')
    .replace(/\r/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  const 告警订单数匹配 = 规范文本.match(/您有[\s|]*(\d+)[\s|]*笔订单剩余处理时间不足[\s|]*5[\s|]*天/);
  const 明细总数匹配 = 规范文本.match(/总共[\s|]*(\d+)[\s|]*条/);
  const 页面警告订单数 = 告警订单数匹配 ? Number(告警订单数匹配[1]) : 0;
  const 及时上传发票订单数 = 提取指标数量(规范文本, '及时上传发票订单数');
  const 应上传发票订单数 = 提取指标数量(规范文本, '应上传发票订单数');
  const 上传指标已识别 = 规范文本.includes('及时上传发票订单数') && 规范文本.includes('应上传发票订单数');
  const 待上传发票订单数 = 上传指标已识别
    ? Math.max(应上传发票订单数 - 及时上传发票订单数, 0)
    : 0;

  return {
    顶部警告已识别: Boolean(告警订单数匹配),
    页面警告订单数,
    警告订单数: 上传指标已识别 ? 待上传发票订单数 : 页面警告订单数,
    及时上传发票订单数,
    应上传发票订单数,
    上传指标已识别,
    待上传发票订单数,
    明细总数: 明细总数匹配 ? Number(明细总数匹配[1]) : 0,
  };
}

function 提取指标数量(规范文本, 指标名称) {
  // 解决：核心指标名称和值会被页面样式拆开，只按指标名后的第一个数字取值。
  const 匹配结果 = String(规范文本 || '').match(new RegExp(`${指标名称}[\\s|:：]*(\\d+)`));
  return 匹配结果 ? Number(匹配结果[1]) : 0;
}

