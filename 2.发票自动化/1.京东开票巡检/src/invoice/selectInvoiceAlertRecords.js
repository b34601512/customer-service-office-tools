const { 筛选需要登记的开票记录 } = require('./invoiceDetailStatus');

function 选择需要提醒的开票记录(选项 = {}) {
  // 解决：优先提醒新增待登记记录，同时补发旧逻辑曾漏掉的存量待登记记录。
  const {
    当前记录 = [],
    新增记录 = [],
    上次指标 = {},
    本次指标 = {},
  } = 选项;
  const 本次待登记数量 = 取待登记数量(本次指标);
  if (本次待登记数量 <= 0) {
    return [];
  }

  const 新增待登记记录 = 筛选需要登记的开票记录(新增记录);
  const 上次待登记数量 = 取待登记数量(上次指标);
  const 需要补发存量记录 = 新增待登记记录.length === 0 && 上次待登记数量 <= 0;
  const 候选记录 = 需要补发存量记录
    ? 筛选需要登记的开票记录(当前记录)
    : 新增待登记记录;

  return 候选记录.slice(0, 本次待登记数量);
}

function 取待登记数量(指标 = {}) {
  // 解决：把新旧指标统一成可比较数量，用于判断是否需要补发漏报。
  const 数字 = Number(指标?.待登记明细数 ?? 指标?.警告订单数 ?? 0);
  if (!Number.isFinite(数字) || 数字 <= 0) {
    return 0;
  }

  return Math.floor(数字);
}

module.exports = {
  选择需要提醒的开票记录,
};
