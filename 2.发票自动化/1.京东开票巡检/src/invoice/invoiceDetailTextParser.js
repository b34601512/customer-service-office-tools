const { 规范化文本 } = require('./normalizeRecord');

function 切分正文令牌(正文文本 = '') {
  // 解决：把页面正文压缩成稳定令牌，便于从非标准表格里恢复明细行。
  return 规范化文本(正文文本)
    .split('|')
    .map((令牌) => 令牌.trim())
    .filter(Boolean);
}

function 是销售订单编号(令牌 = '') {
  // 解决：用订单号作为行起点，比依赖京东前端 DOM 结构更稳定。
  return /^\d{10,}$/.test(String(令牌).trim());
}

function 找到明细数据起点(令牌列表) {
  // 解决：定位“销售订单编号...操作”表头后面的第一条订单记录。
  const 表头起点 = 令牌列表.findIndex((令牌) => /销售订单编号/.test(令牌));
  if (表头起点 < 0) {
    return -1;
  }

  const 操作列索引 = 令牌列表.findIndex((令牌, 索引) => 索引 >= 表头起点 && /^操作$/.test(令牌));
  return 操作列索引 >= 0 ? 操作列索引 + 1 : -1;
}

function 从页面正文解析明细记录(正文文本 = '') {
  // 解决：当京东把表格渲染成难抓的组件时，从可见正文里恢复订单明细。
  const 令牌列表 = 切分正文令牌(正文文本);
  const 起点 = 找到明细数据起点(令牌列表);
  if (起点 < 0) {
    return [];
  }

  const 记录列表 = [];
  let 当前索引 = 起点;
  while (当前索引 < 令牌列表.length) {
    const 当前令牌 = 令牌列表[当前索引];
    if (/^(暂无数据|总共|咨询|反馈|调研|Copyright)/.test(当前令牌)) {
      break;
    }

    if (!是销售订单编号(当前令牌)) {
      当前索引 += 1;
      continue;
    }

    const 行令牌 = 令牌列表.slice(当前索引, 当前索引 + 6);
    if (行令牌.length < 5) {
      break;
    }

    记录列表.push({
      source: '页面文本明细',
      行序号: 记录列表.length + 1,
      销售订单编号: 行令牌[0],
      发票上传的倒计时开始时间: 行令牌[1],
      最晚上传时间: 行令牌[2],
      发票上传时间: 行令牌[3],
      '发票上传倒计时（天）': 行令牌[4],
      操作: 行令牌[5] || '',
    });
    当前索引 += 6;
  }

  return 记录列表;
}

module.exports = {
  从页面正文解析明细记录,
};
