const test = require('node:test');
const assert = require('node:assert/strict');
const { 从页面正文解析明细记录 } = require('../src/invoice/invoiceDetailTextParser');

test('从页面正文恢复未逾期明细行', () => {
  const 记录列表 = 从页面正文解析明细记录([
    '明细数据',
    '销售订单编号 发票上传的倒计时开始时间',
    '最晚上传时间',
    '发票上传时间',
    '发票上传倒计时（天）',
    '操作',
    '3479429018358831',
    '2026-04-29 12:09:17',
    '2026-05-09 12:09:17',
    '2026-05-06 14:13:59',
    '未逾期',
    '去开票',
    '总共1条。',
  ].join('\n'));

  assert.equal(记录列表.length, 1);
  assert.equal(记录列表[0].销售订单编号, '3479429018358831');
  assert.equal(记录列表[0]['发票上传倒计时（天）'], '未逾期');
});

test('从页面正文恢复多条明细行', () => {
  const 记录列表 = 从页面正文解析明细记录([
    '销售订单编号 发票上传的倒计时开始时间',
    '最晚上传时间',
    '发票上传时间',
    '发票上传倒计时（天）',
    '操作',
    '3476275003020679',
    '2026-04-30 19:03:56',
    '2026-05-10 19:03:56',
    '-',
    '还有3天逾期',
    '去开票',
    '3478223018065109',
    '2026-04-28 12:07:56',
    '2026-05-08 12:07:56',
    '2026-05-06 14:20:25',
    '未逾期',
    '去开票',
    '总共2条。',
  ].join('\n'));

  assert.equal(记录列表.length, 2);
  assert.equal(记录列表[0]['发票上传倒计时（天）'], '还有3天逾期');
  assert.equal(记录列表[1]['发票上传倒计时（天）'], '未逾期');
});
