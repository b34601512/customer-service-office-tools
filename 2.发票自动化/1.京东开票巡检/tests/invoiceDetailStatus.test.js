const test = require('node:test');
const assert = require('node:assert/strict');
const {
  识别开票明细状态,
  补充开票明细状态,
  统计开票明细状态,
  筛选需要登记的开票记录,
} = require('../src/invoice/invoiceDetailStatus');

test('未逾期明细识别为已上传且不需要报警', () => {
  const 状态 = 识别开票明细状态({
    销售订单编号: '3479429018358831',
    发票上传时间: '2026-05-06 14:13:59',
    '发票上传倒计时（天）': '未逾期',
  });

  assert.equal(状态.状态, '已上传未逾期');
  assert.equal(状态.需要登记, false);
  assert.equal(状态.需要预警, false);
});

test('还有几天逾期明细识别为待登记预警', () => {
  const 状态 = 识别开票明细状态({
    销售订单编号: '3476275003020679',
    发票上传时间: '-',
    '发票上传倒计时（天）': '还有3天逾期',
  });

  assert.equal(状态.状态, '待登记即将逾期');
  assert.equal(状态.需要登记, true);
  assert.equal(状态.需要预警, true);
});

test('还有 8 天逾期明细识别为待登记但不是最后预警', () => {
  const 状态 = 识别开票明细状态({
    销售订单编号: '3489470007408765',
    发票上传时间: '-',
    '发票上传倒计时（天）': '还有8天逾期',
  });

  assert.equal(状态.状态, '待登记未到预警期');
  assert.equal(状态.需要登记, true);
  assert.equal(状态.需要预警, false);
});

test('倒计时字段不是未逾期时不能被发票上传时间误判为已上传', () => {
  const 状态 = 识别开票明细状态({
    销售订单编号: '3476275003020679',
    发票上传时间: '2026-05-06 14:20:25',
    '发票上传倒计时（天）': '还有2天逾期',
  });

  assert.equal(状态.状态, '待登记即将逾期');
  assert.equal(状态.需要登记, true);
  assert.equal(状态.需要预警, true);
});

test('统计时未逾期只记录状态，不计入待登记和有效告警', () => {
  const 记录列表 = [
    补充开票明细状态({
      销售订单编号: '3476275003020679',
      发票上传时间: '-',
      '发票上传倒计时（天）': '还有3天逾期',
    }),
    补充开票明细状态({
      销售订单编号: '3478223018065109',
      发票上传时间: '2026-05-06 14:20:25',
      '发票上传倒计时（天）': '未逾期',
    }),
    补充开票明细状态({
      销售订单编号: '3477209008120436',
      发票上传时间: '2026-05-06 14:21:07',
      '发票上传倒计时（天）': '未逾期',
    }),
  ];

  const 统计 = 统计开票明细状态(记录列表, {
    警告订单数: 1,
    明细总数: 3,
  });

  assert.equal(统计.页面警告订单数, 1);
  assert.equal(统计.有效警告订单数, 1);
  assert.equal(统计.待登记明细数, 1);
  assert.equal(统计.已上传未逾期数, 2);
});

