test('筛选需要登记记录会排除未逾期记录', () => {
  const 需要提醒记录 = 筛选需要登记的开票记录([
    { summary: '订单 1 | 未逾期' },
    { summary: '订单 2 | 还有3天逾期' },
  ]);

  assert.equal(需要提醒记录.length, 1);
  assert.match(需要提醒记录[0].summary, /还有3天逾期/);
});
