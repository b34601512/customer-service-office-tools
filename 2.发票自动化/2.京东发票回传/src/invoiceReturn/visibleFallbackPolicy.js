const 需要可见浏览器处理关键词 = [
  '登录态失效',
  '等待登录完成超时',
  '请先完成登录',
  '可见登录',
  '验证码',
  '滑块',
  '短信验证',
  '短信二次验证',
  '身份认证',
  '安全验证',
  '人工确认',
  '扫码登录',
  '京东登录',
];

function 读取错误完整消息(错误) {
  // 解决：人工介入判断只看错误链里的文字，不让判断逻辑散落到各层。
  const 消息列表 = [];
  let 当前错误 = 错误;
  while (当前错误) {
    消息列表.push(String(当前错误?.message || 当前错误 || '').trim());
    当前错误 = 当前错误?.cause;
  }
  return 消息列表.filter(Boolean).join('\n');
}

function 是需要可见浏览器处理的回传错误(错误) {
  // 解决：只有登录和安全验证这类后台无法完成的情况才打开可见浏览器。
  const 错误消息 = 读取错误完整消息(错误);
  return 需要可见浏览器处理关键词.some((关键词) => 错误消息.includes(关键词));
}

module.exports = {
  是需要可见浏览器处理的回传错误,
};
