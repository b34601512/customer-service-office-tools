const { 项目根目录 } = require('./paths');
const { 读取发布信息 } = require('./releaseInfo');
const {
  作者名称,
  作者微信,
  官方网站域名,
  构建应用展示信息: 构建通用应用展示信息,
} = require('../../../共享CLI/应用元信息');

const 应用名称 = '京东催促开票记录';

function 构建应用展示信息(发布信息) {
  // 解决：把首页展示字段集中收口，避免作者信息散落在页面和脚本里。
  return 构建通用应用展示信息({
    应用名称,
    显示版本: 发布信息?.显示版本,
  });
}

function 读取应用展示信息() {
  // 解决：主界面始终读取项目真实发布版本，避免界面版本和分发版本不一致。
  const 发布信息 = 读取发布信息(项目根目录, {
    严格校验打包配置: false,
  });
  return 构建应用展示信息(发布信息);
}

module.exports = {
  应用名称,
  作者名称,
  作者微信,
  官方网站域名,
  构建应用展示信息,
  读取应用展示信息,
};
