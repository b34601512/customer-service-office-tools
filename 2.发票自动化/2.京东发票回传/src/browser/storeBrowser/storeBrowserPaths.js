const fs = require('fs');
const {
  获取店铺浏览器目录,
  获取店铺登录态文件路径,
} = require('../../common/paths');

function 解析店铺浏览器参数(选项 = {}) {
  // 解决：浏览器入口必须绑定真实店铺，避免不同店铺登录态互相污染。
  const 店铺标识 = String(选项.店铺标识 || '').trim();
  if (!店铺标识) {
    throw new Error('浏览器启动失败：必须传入真实店铺标识。');
  }
  return {
    店铺标识,
    旧浏览器目录: 选项.旧浏览器目录路径 || 获取店铺浏览器目录(店铺标识),
    登录态文件路径: 选项.登录态文件路径 || 获取店铺登录态文件路径(店铺标识),
  };
}

function 店铺登录态文件存在(登录态文件路径) {
  // 解决：只在真实存在登录态文件时才传给 Playwright，避免空路径导致启动失败。
  return fs.existsSync(登录态文件路径);
}

module.exports = {
  解析店铺浏览器参数,
  店铺登录态文件存在,
};
