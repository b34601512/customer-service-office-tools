#!/usr/bin/env node
// 催促判定（全平台通用 · 2026-09-22 用户拍板）——纯函数，不发消息、不点任何按钮。
//
// 退货退款类的树（见 经验/催促通用原则.md）：
//   1) 未签收 → 不催（在途）
//   2) 已签收 → 查金山《退货退款对接表》：
//        表里有 + 平台没退款 → 催
//        表里有 + 平台已退款 → 不催
//        表里没有 + 签收 > 24h → 催（漏登记）
//        表里没有 + 签收 ≤ 24h → 不催（给登记时间）
//   3) 签收状态/签收时间读不到 → 标「待确认签收」并要人来看，**不许**当“未签收”判无漏
//
// 各平台工具只负责把三样事实喂进来：
//   签收状态: "signed" | "in_transit" | "unknown"
//   签收时间: ISO 字符串（或 null）
//   退货表  : "已登记" | "已退款" | "未登记" | null   ← 金山《退货退款对接表》
//   平台退款: "已退款" | "未退款" | null             ← 平台自己那一侧
const 签收超时小时 = 24;

function 判定退货催促({ 签收状态, 签收时间 = null, 退货表 = null, 平台退款 = null, now = Date.now() } = {}) {
  if (签收状态 !== "signed") {
    if (签收状态 === "in_transit") {
      return { 催: false, 分支: "未签收-在途", 理由: "退货在途、未签收，不催", 需人工: false };
    }
    return {
      催: false, 分支: "签收未知", 需人工: true,
      理由: "签收状态读不到，标「待确认签收」停下来问人，不许当成未签收去判无漏"
    };
  }

  const 表里有 = 退货表 === "已登记" || 退货表 === "已退款";
  const 平台已退款 = 平台退款 === "已退款";

  if (表里有) {
    if (平台已退款) return { 催: false, 分支: "表里有+平台已退款", 理由: "退货表已登记且平台已退款，办完了", 需人工: false };
    return { 催: true, 分支: "表里有+平台未退款", 理由: "退货表已登记但平台还没退款 → 催", 需人工: false };
  }

  // 表里没有
  if (平台已退款) return { 催: false, 分支: "表里没有+平台已退款", 理由: "平台已退款，办完（登记表漏登只作记账提醒）", 需人工: false };
  if (!签收时间 || Number.isNaN(new Date(签收时间).getTime())) {
    return { 催: false, 分支: "签收时间缺失", 理由: "读不到签收时间、算不出 24 小时，先人工确认", 需人工: true };
  }
  const 小时 = (now - new Date(签收时间).getTime()) / 3600000;
  if (小时 > 签收超时小时) {
    return { 催: true, 分支: "表里没有+签收超24小时", 理由: `签收已 ${小时.toFixed(1)} 小时仍未登记退货表 → 催`, 需人工: false };
  }
  return { 催: false, 分支: "表里没有+签收不足24小时", 理由: `签收才 ${小时.toFixed(1)} 小时，给客服登记时间`, 需人工: false };
}

// 话术按“表里有没有登记”定（禁止表里没登记却说“已登记”）
function 退货催促话术({ 签收时间 = null, 退货表 = null, 自动退款截止 = null } = {}) {
  const 表里有 = 退货表 === "已登记" || 退货表 === "已退款";
  const 签收于 = 签收时间 ? new Date(签收时间).toLocaleString("zh-CN", { hour12: false }) : "签收时间待确认";
  if (表里有) return `客户已退货（退款表已登记，签收于 ${签收于}），请尽快给客户退款。`;
  const 尾 = 自动退款截止 ? `，否则平台 ${自动退款截止} 后自动退款` : "";
  return `买家已寄回并签收（${签收于}），请确认收货并登记退货表${尾}。`;
}

module.exports = { 判定退货催促, 退货催促话术, 签收超时小时 };
